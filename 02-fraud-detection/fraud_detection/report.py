"""Render the model card and decision memo from results/. No number is typed here.

python -m fraud_detection.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict, long: bool = True) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != "creditcard_openml":
        text = "Generated from a fast or synthetic run. Do not cite these numbers."
        return f"> **Not a release result.** {text}\n\n"
    return ""


def _pct(x) -> str:
    return "n/a" if x is None else f"{x:.1%}"


def render_model_card(metrics: dict, analysis: dict) -> str:
    head, calib = metrics["headline"], metrics["calibration"]
    split, traps = metrics["split"], metrics["traps"]
    rows = "\n".join(
        f"| {n} | {r['val_pr_auc']:.4f} | {r['test_pr_auc']:.4f} | {r['test_roc_auc']:.4f} | {r['test_brier']:.6f} |"
        for n, r in metrics["models"].items()
    )
    cost_rows = "\n".join(
        f"| {c} | {v['flag_nothing']:,.0f} | {v['flag_everything']:,.0f} | {v['global_threshold_tuned_on_val']:,.0f} | "
        f"{v['per_transaction_sigmoid']:,.0f} | {v['per_transaction_isotonic']:,.0f} | {v['oracle_threshold_tuned_on_test']:,.0f} |"
        for c, v in metrics["cost_by_review_cost"].items()
    )
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    acc, opt, rs = traps["accuracy"], traps["threshold_on_test"], traps["random_split"]
    return f"""# Model card: fraud detection

{_banner(metrics)}Generated by `python -m fraud_detection.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating a rare-event classifier with ranking, calibration, and cost metrics. Not for deciding which real transactions to block.

## Data
Credit card transactions, {metrics["data"]["rows"]:,} rows, {metrics["data"]["fraud_rows"]:,} fraud ({metrics["data"]["fraud_rate"]:.4%}). {metrics["data"]["duplicate_rows"]:,} duplicate rows kept. See `data/DATA_CARD.md`.

## Split
{split["strategy"]}. Fit {split["fit_rows"]:,} rows ({split["fit_fraud"]} fraud), validation {split["val_rows"]:,} ({split["val_fraud"]} fraud), test {split["test_rows"]:,} ({split["test_fraud"]} fraud, rate {split["test_fraud_rate"]:.4%}).

## Ranking quality
PR-AUC is average precision. A constant scorer gets the test fraud rate.

| Model | Val PR-AUC | Test PR-AUC | Test ROC-AUC | Test Brier |
|---|---|---|---|---|
{rows}

Headline: **{head["model"]}**, chosen by validation PR-AUC. Test PR-AUC {head["value"]:.4f}, 95% interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f} ({head["ci_method"]}). Constant baseline {metrics["baseline"]["test_pr_auc"]:.4f}.

## Calibration
Brier raw {calib["test_brier_raw"]:.6f}, sigmoid {calib["test_brier_sigmoid"]:.6f}, isotonic {calib["test_brier_isotonic"]:.6f}, constant prevalence {calib["test_brier_constant_prevalence"]:.6f}. Sum of predicted over actual fraud: raw {calib["test_calibration_ratio_raw"]:.2f}, sigmoid {calib["test_calibration_ratio_sigmoid"]:.2f}, isotonic {calib["test_calibration_ratio_isotonic"]:.2f} (1.00 is calibrated in the large). Calibrators are fitted on validation, which holds {calib["val_fraud_rows"]} fraud rows.

## Cost under stated assumptions
Missed fraud costs its amount. A flag costs the review cost in the first column. Values are in the dataset's currency units on the test set. The review costs are assumptions.

| Review cost | Flag nothing | Flag everything | Global threshold (val) | Per-transaction (sigmoid) | Per-transaction (isotonic) | Threshold tuned on test |
|---|---|---|---|---|---|---|
{cost_rows}

Gap in cost, global threshold minus per-transaction rule, at the base review cost: 95% interval {metrics["cost_gap_global_minus_per_transaction_ci95"][0]:,.0f} to {metrics["cost_gap_global_minus_per_transaction_ci95"][1]:,.0f}.

## The traps, measured
- Accuracy: always predicting legitimate scores {acc["constant_legit_accuracy"]:.4%}. The model at its cost threshold scores {acc["model_accuracy_at_global_threshold"]:.4%} and catches {_pct(acc["model_recall_at_global_threshold"])} of fraud.
- Tuning the threshold on test: cost {opt["cost_with_threshold_tuned_on_val"]:,.0f} with a validation threshold versus {opt["cost_with_threshold_tuned_on_test"]:,.0f} with a test threshold. The difference of {opt["optimism"]:,.0f} is optimism you cannot get in practice.
- Random split: PR-AUC {rs["random_split_test_pr_auc"]:.4f} on a random split against {rs["time_split_test_pr_auc"]:.4f} on the time split. {rs["note"]}

## Where it fails
Lowest recall amount band with at least 10 fraud rows: **{analysis["lowest_recall_amount_band_min_10_fraud"]}**. Overall recall of the policy: {_pct(analysis["overall"]["recall"])}. Full tables are in `results/error_analysis.json`.

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, scikit-learn {metrics["versions"]["scikit-learn"]}, pandas {metrics["versions"]["pandas"]}, numpy {metrics["versions"]["numpy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    head, gate = metrics["headline"], metrics["gate"]
    base = metrics["cost_by_review_cost"][str(config.REVIEW_COST_BASE)]
    verdict = "PASS" if gate["passed"] else "FAIL"
    saving = base["saving_vs_best_trivial_per_transaction"]
    gap_low, gap_high = metrics["cost_gap_global_minus_per_transaction_ci95"]
    if gap_low > 0:
        gap_text = "The interval is above zero, so the per-transaction rule is cheaper."
    elif gap_high < 0:
        gap_text = "The interval is below zero, so the global threshold is cheaper."
    else:
        gap_text = "The interval spans zero, so the data does not show that either rule is cheaper."
    return f"""# Decision memo: fraud screening model

{_banner(metrics)}Generated by `python -m fraud_detection.report` from `results/`. Do not edit by hand.

## The question
Should transactions be flagged for manual review using this model, and by which rule?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
- Ranking: headline {head["model"]} has test PR-AUC {head["value"]:.4f}, interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f}, against a constant baseline of {metrics["baseline"]["test_pr_auc"]:.4f}. Interval above baseline: {gate["pr_auc_interval_above_baseline"]}.
- Cost: at a review cost of {config.REVIEW_COST_BASE}, the per-transaction rule costs {base["per_transaction_sigmoid"]:,.0f}. The best trivial policy costs {base["best_trivial"]:,.0f}. Saving versus the best trivial policy: {_pct(saving)}. Beats trivial: {gate["per_transaction_policy_beats_trivial"]}.

- Rule comparison: the cost gap between the validation-tuned global threshold and the per-transaction rule has a 95% interval of {gap_low:,.0f} to {gap_high:,.0f} at the base review cost. {gap_text}

## What the cost depends on
The review cost is an assumption. The memo is not valid for any real operation until the real review cost and the real loss per missed fraud replace it. The sensitivity table in the model card shows how the answer moves across the tested review costs.

## Where not to trust it
Lowest recall amount band: {analysis["lowest_recall_amount_band_min_10_fraud"]}. The test period is short, so drift over time is untested.

## Not done
No per-card or per-merchant features. No drift monitoring. No fairness analysis. No retraining schedule. No analyst capacity limit on how many flags can be reviewed.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
