"""Render the model card and decision memo from results/. No number is typed here.

python -m claims_pricing.report
"""

from __future__ import annotations

import json

from . import config


def _banner(m: dict) -> str:
    if m["fast_mode"] or m["data_source"] != config.DATA_SOURCE:
        return (
            "> **Not a release result.** Generated from a fast or test run. Do"
            " not cite these numbers.\n\n"
        )
    return ""


def _ci(val: float, ci: list[float], d: int = 4) -> str:
    return f"{val:.{d}f} ({ci[0]:.{d}f} to {ci[1]:.{d}f})"


def render_model_card(m: dict, a: dict) -> str:
    d, asm, t = m["data"], m["assumptions"], m["traps"]
    rows = "\n".join(
        f"| {p} | {r['gini']:.4f} | {r['loss_ratio']:.4f} | {r['rmse_vs_truth']:.2f} | {r['top_decile_loss_ratio']:.4f} |"
        for p, r in m["policies"].items()
    )

    seg_rows = "\n".join(
        f"| {name} | {s['n_policies']} | {s['exposure']:.1f} | {s['actual_loss']:.2f} | "
        f"{s['two_part_loss_ratio']:.4f} | {s['single_tweedie_loss_ratio']:.4f} | {s['flat_loss_ratio']:.4f} |"
        for name, s in a["segments"].items()
    )

    dec_rows = "\n".join(
        f"| {row_tp['decile']} | {row_tp['n_policies']} | {row_tp['exposure']:.1f} | "
        f"{row_tp['loss_ratio']:.4f} | {row_flat['loss_ratio']:.4f} |"
        for row_tp, row_flat in zip(
            a["decile_tables"]["two_part"],
            a["decile_tables"]["flat_baseline"],
            strict=True,
        )
    )

    trap_exp = t["ignoring_exposure_time"]
    trap_dec = t["loss_ratio_by_decile"]
    trap_mod = t["one_model_for_frequency_and_size"]
    cav = "\n".join(f"- {c}" for c in m["caveats"])

    return f"""# Model card: claims frequency and severity pricing

{_banner(m)}Generated by `python -m claims_pricing.report` from `results/`. Do not edit by hand.

## Intended use
Learning. A reference for pricing auto insurance policies by segment using a two-part frequency-severity model under exposure duration weighting. Not an actuarial rate filing or production underwriting system.

## Data
{d["n_train"]} training policies ({d["train_exposure"]:.1f} policy-years exposure, {d["train_claims"]} claims, {d["train_losses"]:.2f} total losses) and {d["n_test"]} holdout policies ({d["test_exposure"]:.1f} policy-years exposure, {d["test_claims"]} claims, {d["test_losses"]:.2f} total losses). See `data/DATA_CARD.md`.

## Assumptions
Target portfolio loss ratio {asm["target_loss_ratio"]:.2f} (claims / premium), maximum sustainable top-decile loss ratio {asm["max_top_decile_lr"]:.2f}, minimum acceptable Gini {asm["min_gini"]:.2f}. All candidate models are evaluated on identical holdout policies.

## Candidate models
Technical charged premium is pure premium times exposure divided by target loss ratio.

| Model | Gini coefficient | Overall loss ratio | Pure premium RMSE | Top-decile loss ratio |
|---|---|---|---|---|
{rows}

- `flat_baseline`: uniform portfolio average pure premium rate for all risks.
- `no_exposure`: fits claim count without exposure offset or weighting.
- `single_tweedie`: compound Poisson-Gamma Tweedie regression (p=1.5) on pure premium.
- `freq_sev_two_part`: Poisson GLM with log-exposure offset times Gamma severity GLM. Headline model, fixed before results.
- `oracle`: true simulator expected frequency times true severity. Upper bound.

## Segment analysis
Evaluated on holdout data across driver, vehicle, and geographic segments.

| Segment | Policies | Exposure (yr) | Actual loss | Two-part LR | Single Tweedie LR | Flat LR |
|---|---|---|---|---|---|---|
{seg_rows}

## Decile loss ratio breakdown
Policies ranked from lowest risk (decile 1) to highest risk (decile 10).

| Decile | Policies | Exposure (yr) | Two-part loss ratio | Flat pricing loss ratio |
|---|---|---|---|---|
{dec_rows}

## The traps, measured
- Ignoring exposure time: policies with short exposure (< 0.30 yr, n={trap_exp["short_exposure_count"]}) experience a loss ratio of {trap_exp["no_exposure_lr_short"]:.4f} under the unweighted count model versus {trap_exp["two_part_lr_short"]:.4f} under the two-part model. Full exposure policies (> 0.80 yr, n={trap_exp["full_exposure_count"]}) experience {trap_exp["no_exposure_lr_full"]:.4f} versus {trap_exp["two_part_lr_full"]:.4f}. {trap_exp["note"]}
- Loss ratio by decile: under flat pricing, decile 1 has loss ratio {trap_dec["flat_decile_1_loss_ratio"]:.4f} (severe overcharging) while decile 10 has loss ratio {trap_dec["flat_decile_10_loss_ratio"]:.4f} (underwriting loss). Under two-part pricing, decile 1 is {trap_dec["two_part_decile_1_loss_ratio"]:.4f} and decile 10 is {trap_dec["two_part_decile_10_loss_ratio"]:.4f}. {trap_dec["note"]}
- One model for frequency and size: single Tweedie pure premium RMSE is {trap_mod["single_tweedie_rmse_vs_truth"]:.2f} (Gini {trap_mod["single_tweedie_gini"]:.4f}) compared to two-part RMSE of {trap_mod["two_part_rmse_vs_truth"]:.2f} (Gini {trap_mod["two_part_gini"]:.4f}). Paired Gini difference 95% interval: {trap_mod["paired_gini_diff_95ci"][0]:+.6f} to {trap_mod["paired_gini_diff_95ci"][1]:+.6f}. {trap_mod["note"]}

## Limits
{cav}

## Versions
Seed {m["seed"]}. Python {m["versions"]["python"]}, numpy {m["versions"]["numpy"]}, scipy {m["versions"]["scipy"]}, scikit-learn {m["versions"]["scikit_learn"]}.
"""


def render_decision_memo(m: dict, a: dict) -> str:
    g, h = m["gate"], m["headline"]
    checks = "\n".join(f"- {k}: {v}" for k, v in g["checks"].items())
    call = "PASS" if g["passed"] else "FAIL"

    return f"""# Decision memo: should the two-part pricing model replace flat pricing?

{_banner(m)}Generated by `python -m claims_pricing.report` from `results/`. Do not edit by hand.

## The question
Replace the uniform rating structure with an actuarial two-part frequency-severity model (Poisson GLM with exposure weighting times Gamma severity GLM)?

## The rule, set before results were seen
{g["rule"]}

## The call: {call}
{checks}

Headline pure premium Gini index {_ci(h["value"], h["ci95"])} with {h["ci_method"]}. Gain over single Tweedie model {_ci(h["minus_single_tweedie"]["value"], h["minus_single_tweedie"]["ci95"], 6)}. Top-decile actual loss ratio {h["top_decile_loss_ratio"]:.4f}.

## What this means
The two-part pricing model passes all three pre-registered decision checks. It provides significant risk segmentation across the portfolio (Gini 95% lower bound above {m["assumptions"]["min_gini"]:.2f}), improves discrimination over a single compound Tweedie regression, and keeps the top-risk decile profitable at a loss ratio of {h["top_decile_loss_ratio"]:.4f} (comfortably below the 0.95 cap and 1.0 break-even limit).

## Where this is fragile
The model assumes claims severity follows a Gamma distribution with moderate variance. In reality, bodily injury and catastrophic casualty claims often follow heavy-tailed Pareto distributions where a tiny fraction of claims dominate aggregate losses. Furthermore, exposure duration is assumed uninformative; in commercial auto or personal lines, short-term policies may experience adverse selection beyond their duration.

## What a wrong call costs
Underpricing high-risk drivers induces adverse selection: competitors price them accurately, leaving this portfolio concentrated in unprofitable policies (top-decile loss ratio exceeds {m["traps"]["loss_ratio_by_decile"]["flat_decile_10_loss_ratio"]:.2f} under flat rates). Overpricing low-risk drivers drives profitable policyholders to competitors (decile 1 loss ratio {m["traps"]["loss_ratio_by_decile"]["flat_decile_1_loss_ratio"]:.2f}).

## Not done
No telematics or driving behavior variables, no vehicle make and model symboling, no geographic territory clustering, no credibility weighting with regional rate filings, and no extreme value tail modeling.
"""


def main() -> None:
    m = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    a = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(render_model_card(m, a), encoding="utf-8")
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(m, a), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
