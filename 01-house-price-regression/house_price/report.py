"""Render the model card and decision memo from results/. No number is typed here.

python -m house_price.report
"""

from __future__ import annotations

import json

from . import config

DOLLARS_PER_UNIT = 100_000  # target is in units of $100,000


def _usd(units: float) -> str:
    return f"${units * DOLLARS_PER_UNIT:,.0f}"


def render_model_card(metrics: dict, analysis: dict) -> str:
    head = metrics["headline"]
    base = metrics["best_baseline"]
    trap = metrics["leakage_trap"]
    rows = []
    for name, res in metrics["models"].items():
        rows.append(
            f"| {name} | {res['cv_rmse']:.4f} | {res['test_rmse']:.4f} | "
            f"{res['test_mae']:.4f} | {res['test_r2']:.4f} |"
        )
    table = "\n".join(rows)
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    banner = ""
    if metrics["fast_mode"] or metrics["data_source"] != "california_housing":
        banner = (
            "> **Not a release result.** Generated from a fast or synthetic run. "
            "Do not cite these numbers.\n\n"
        )
    return f"""# Model card: house price regression

{banner}Generated by `python -m house_price.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for how to evaluate a regression model honestly. Not for valuing real property or making decisions about people.

## Data
California Housing, 1990 census block groups. {metrics["data"]["rows"]:,} rows. {metrics["data"]["censored_rows"]:,} rows ({metrics["data"]["censored_share"]:.1%}) are censored at the target cap. See `data/DATA_CARD.md`.

## Split
{metrics["split"]["strategy"]}. {metrics["split"]["train_rows"]:,} train rows in {metrics["split"]["train_cells"]} cells, {metrics["split"]["test_rows"]:,} test rows in {metrics["split"]["test_cells"]} cells. No cell appears on both sides.

## Results
Units are $100,000 (1990 dollars). Cross-validation is grouped by cell, on train rows only. Test rows were scored once after the headline model was chosen by CV.

| Model | CV RMSE | Test RMSE | Test MAE | Test R2 |
|---|---|---|---|---|
{table}

Headline: **{head["model"]}**, test RMSE {head["value"]:.4f} ({_usd(head["value"])}), 95% interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f} ({head["ci_method"]}). Best baseline: {base["model"]}, test RMSE {base["test_rmse"]:.4f}.

## The leakage trap
Same model and hyperparameters. Random split test RMSE {trap["random_split_test_rmse"]:.4f}. Spatial split test RMSE {trap["spatial_split_test_rmse"]:.4f}. Difference {trap["difference"]:+.4f}. {trap["note"]}

## Where it fails
Worst segment with at least 30 test rows: **{analysis["worst_segment_min_n_30"]}**. Overall bias (predicted minus actual): {analysis["overall"]["bias"]:+.4f}. Full tables are in `results/error_analysis.json`.

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, scikit-learn {metrics["versions"]["scikit-learn"]}, pandas {metrics["versions"]["pandas"]}, numpy {metrics["versions"]["numpy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    head = metrics["headline"]
    base = metrics["best_baseline"]
    gate = metrics["gate"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    trap = metrics["leakage_trap"]
    banner = ""
    if metrics["fast_mode"] or metrics["data_source"] != "california_housing":
        banner = "> **Not a release result.** Generated from a fast or synthetic run.\n\n"
    worst = analysis["worst_segment_min_n_30"]
    return f"""# Decision memo: house price model

{banner}Generated by `python -m house_price.report` from `results/`. Do not edit by hand.

## The question
Can this model be used as a first-pass screen for median house value in a block group, and is it better than guessing a constant?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline model {head["model"]} has test RMSE {head["value"]:.4f} ({_usd(head["value"])}), 95% interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f}. The best constant baseline ({base["model"]}) has test RMSE {base["test_rmse"]:.4f} ({_usd(base["test_rmse"])}).

## What a wrong answer costs
The typical miss is about {_usd(head["value"])} in 1990 dollars. Treat that as the scale of error for any single block group, and larger in the weak segment below.

## Where not to trust it
Weakest segment with at least 30 test rows: {worst}. Rows at the price cap are censored, so the model cannot be right about the top of the market.

## The evaluation trap that would have flattered it
A random split scores {trap["random_split_test_rmse"]:.4f} against {trap["spatial_split_test_rmse"]:.4f} on the spatial split, a difference of {trap["difference"]:+.4f}. Report the spatial number.

## Not done
No time-based validation (data is one snapshot). No fairness analysis. No cost-weighted metric, because no real decision costs exist for this teaching dataset.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
