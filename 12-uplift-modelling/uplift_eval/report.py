"""Render the model card and decision memo from results/. No number is typed here.

python -m uplift_eval.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(block: dict, digits: int = 3, signed: bool = False) -> str:
    lo, hi = block["ci95"]
    f = f"{'+' if signed else ''}.{digits}f"
    return f"{block['value']:{f}} ({lo:{f}} to {hi:{f}})"


def _n(x, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def render_model_card(metrics: dict, analysis: dict) -> str:
    p, d, a, t = metrics["policies"], metrics["data"], metrics["assumptions"], metrics["traps"]
    h = metrics["headline"]["learner"]
    rows = "\n".join(
        f"| {n} | {v['treat_share']:.3f} | {_ci(v['estimated_profit'], 2)} | {v['true_profit_population']:.3f} | "
        f"{_n(v['mean_true_effect_of_those_treated'])} | {_n(v['share_treated_with_negative_effect'])} |"
        for n, v in p.items()
    )
    lrows = "\n".join(
        f"| {n} | {_ci(p[n]['qini_coefficient'], 4)} | {p[n]['dev_auuc']:.4f} | {p[n]['corr_with_true_effect']:.3f} | "
        f"{p[n]['true_profit_top_budget_population']:.3f} |"
        for n in config.CANDIDATES
    )
    rt, wc, cf = (
        t["response_model_instead_of_uplift"],
        t["optimistic_profit_estimate"],
        t["offers_that_followed_buying_signals"],
    )
    cf_rows = "\n".join(
        f"| {n} | {v['trained_on_trial']:.3f} | {v['trained_on_observational']:.3f} |"
        for n, v in cf["true_profit_population"].items()
    )
    size_names = list(t["data_needed"][0]["mean_true_profit"])
    size_rows = "\n".join(
        f"| {r['train_customers']} | "
        + " | ".join(f"{r['mean_true_profit'][n]:.3f}" for n in size_names)
        + " |"
        for r in t["data_needed"]
    )
    budget = "\n".join(
        f"| {r['share_treated']:.0%} | {r['headline']:.3f} | {r['response_model']:.3f} | {r['random']:.3f} | {r['oracle']:.3f} |"
        for r in t["budget_curve"]
    )
    seg = "\n".join(
        f"| {r['segment']} | {r['share_of_customers']:.3f} | {r['mean_true_effect']:+.3f} | {r['headline_treats']:.3f} | {r['profit_per_customer_if_treat_all']:+.3f} |"
        for r in analysis["segments"]
    )
    cost = "\n".join(
        f"| {r['cost_per_offer']:g} | {r['threshold']:.3f} | {r['treat_share']:.3f} | {r['true_profit_headline']:.3f} | {r['true_profit_treat_all']:.3f} | {r['true_profit_oracle']:.3f} |"
        for r in analysis["cost_sensitivity"]
    )
    calib = "\n".join(
        f"| {r['decile_of_predicted_uplift']} | {r['mean_predicted']:+.3f} | {r['mean_true']:+.3f} |"
        for r in analysis["calibration_by_decile"]
    )
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    return f"""# Model card: uplift modelling for an offer

{_banner(metrics)}Generated by `python -m uplift_eval.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for deciding whom to make an offer to from a randomised trial: uplift learners, the uplift (Qini) curve, profit by inverse-probability weighting, and a comparison with the true effect. Not a production targeting system.

## Data
Simulated customers with a known individual effect of the offer. {d["train"]} train, {d["dev"]} dev and {d["test"]} test customers from a randomised trial (offer given to {d["treated_share_test"]:.3f} of the test set, conversion rate {d["conversion_rate_test"]:.3f}). A fresh population of {d["population"]} customers gives the true value of each policy. See `data/DATA_CARD.md`.

## Assumptions
A conversion is worth {a["value_per_conversion"]:g} and an offer costs {a["cost_per_offer"]:g}, so an offer pays when the effect on the buying chance exceeds {a["threshold"]:.3f}. Fixed-budget comparisons treat {a["budget_share"]:.0%}. Both numbers are assumptions.

## Policies
Estimated profit is per customer over treating nobody, by inverse-probability weighting on the test trial, with a bootstrap 95% interval. True profit is on the fresh population and needs the simulator. The last two columns use the true effect of the customers the policy offers.

| Policy | Share offered | Estimated profit | True profit | Mean true effect of those offered | Share offered who are harmed |
|---|---|---|---|---|---|
{rows}

Headline: **{h}** ({metrics["headline"]["selected_by"]}). Treat-all minus headline, paired: {_ci(metrics["headline"]["minus_treat_all"], 2, True)} (headline minus treat-all).

## Learners
Qini coefficient is the area between the uplift curve and random targeting, on test, per customer.

| Learner | Qini coefficient | Dev AUUC | Correlation of predicted uplift with true effect | True profit offering the top {a["budget_share"]:.0%} |
|---|---|---|---|---|
{lrows}

## The traps, measured
- A model of who will buy is not a model of who the offer changes. At a {rt["budget_share"]:.0%} budget the uplift model earns {rt["true_profit_uplift_model"]:.3f}, the response model {rt["true_profit_response_model"]:.3f}, random {rt["true_profit_random"]:.3f}, the oracle {rt["true_profit_oracle"]:.3f}. Mean true effect among those offered: {rt["mean_true_effect_targeted_uplift_model"]:.3f} (uplift), {rt["mean_true_effect_targeted_response_model"]:.3f} (response), {rt["mean_true_effect_everyone"]:.3f} (everyone).
- Estimated profit is noisy and shares one sample's luck. For {wc["headline"]}: estimated on training rows {wc["estimated_on_training_rows"]["value"]:.3f}, on dev {wc["estimated_on_dev"]["value"]:.3f}, best of the four on dev {wc["best_dev_estimate_among_candidates"]:.3f}, on test {wc["estimated_on_test"]["value"]:.3f}; the true value is {wc["true_on_population"]:.3f}. Treat-all is estimated at {wc["treat_all_estimated_vs_true_population"][0]:.3f} against a truth of {wc["treat_all_estimated_vs_true_population"][1]:.3f}, and the oracle at {wc["oracle_estimated_vs_true_population"][0]:.3f} against {wc["oracle_estimated_vs_true_population"][1]:.3f}. Every absolute estimate sits above its truth, because they share the same outcomes. {wc["note"]}
- Offers that followed buying signals: the naive buyers-minus-non-buyers gap is {cf["naive_effect_in_observational_data"]:.3f} in the observational data and {cf["naive_effect_in_trial"]:.3f} in the trial; the true average effect is {cf["true_average_effect"]:.3f}. {cf["note"]}

| Learner | True profit, trained on the trial | True profit, trained on the observational data |
|---|---|---|
{cf_rows}

### How much data?
Mean true profit over {t["data_needed"][0]["replications"]} replications.

| Training customers | {" | ".join(size_names)} |
|---|{"---|" * len(size_names)}
{size_rows}

### Profit by share offered
True profit on the population when the top share by each score is offered.

| Share offered | Headline | Response model | Random | Oracle |
|---|---|---|---|---|
{budget}

## Where the headline errs
By true effect of the customer:

| Customers for whom | Share | Mean true effect | Share the headline offers | Profit per customer if offered to all |
|---|---|---|---|---|
{seg}

Predicted against true uplift, by decile of predicted uplift:

| Decile | Mean predicted | Mean true |
|---|---|---|
{calib}

### Sensitivity to the cost of an offer
The same predictions with the threshold moved to cost over value.

| Cost per offer | Threshold | Share offered | True profit, headline | True profit, offer to all | True profit, oracle |
|---|---|---|---|---|---|
{cost}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    hd, gate, p, t = metrics["headline"], metrics["gate"], metrics["policies"], metrics["traps"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    h = hd["learner"]
    seg = analysis["segments"]
    small = t["data_needed"][0]
    best_small = max(small["mean_true_profit"], key=lambda k: small["mean_true_profit"][k])
    big = t["data_needed"][-1]
    rt, cf = t["response_model_instead_of_uplift"], t["offers_that_followed_buying_signals"]
    obs_loss = [
        v["trained_on_trial"] - v["trained_on_observational"]
        for v in cf["true_profit_population"].values()
    ]
    return f"""# Decision memo: whom should we send the offer to?

{_banner(metrics)}Generated by `python -m uplift_eval.report` from `results/`. Do not edit by hand.

## The question
Offer a discount to everyone, to nobody, or to a chosen group. Can a model trained on a randomised trial pick the group, and is it better than blanket offers?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline learner: {h}.
{checks}

Estimated incremental profit per customer {_ci({"value": hd["value"], "ci95": hd["ci95"]}, 2)}. Against offering everyone: {_ci(hd["minus_treat_all"], 2, True)}. Qini coefficient {_ci(hd["qini_coefficient"], 4)}. On a large fresh population the true profit is {hd["true_profit_population"]:.3f}, against {p["treat_all"]["true_profit_population"]:.3f} for offering everyone and {p["oracle"]["true_profit_population"]:.3f} for a policy that knows each customer's effect.

## What the model gets right
{seg[0]["share_of_customers"]:.0%} of customers buy less when offered. Offering everyone loses {-seg[0]["profit_per_customer_if_treat_all"]:.2f} per customer on them. The headline offers to {seg[0]["headline_treats"]:.1%} of that group and to {seg[2]["headline_treats"]:.1%} of the group for whom the offer pays.

## Where this result is fragile
- Data. With {small["train_customers"]} training customers the best learner was {best_small} ({small["mean_true_profit"][best_small]:.3f}) and the headline learner scored {small["mean_true_profit"][h]:.3f}. With {big["train_customers"]} they are within {max(big["mean_true_profit"].values()) - min(big["mean_true_profit"].values()):.2f} of each other. This pass is for a trial of {metrics["data"]["train"]} customers and a strong effect.
- Choosing a learner on dev AUUC among four near-equal models is close to a coin flip. Their Qini intervals overlap.
- A response model that predicts who will buy earns {rt["true_profit_response_model"]:.3f} at a {rt["budget_share"]:.0%} budget against {rt["true_profit_uplift_model"]:.3f} for an uplift model.
- Training on past offers that followed buying signals cost between {min(obs_loss):.2f} and {max(obs_loss):.2f} in true profit per customer and gave a naive effect of {cf["naive_effect_in_observational_data"]:.2f} against a true {cf["true_average_effect"]:.2f}. Use trial data.
- Absolute profit estimates from one trial all sat above their truth because they share the same outcomes. Compare policies by paired differences, as the gate does.

## What a wrong call costs
Offering to everyone costs the harmed group their purchases and the rest the offer cost. Offering to nobody gives up the profit the right group would bring. The money values are assumptions: {metrics["assumptions"]["value_per_conversion"]:g} per conversion and {metrics["assumptions"]["cost_per_offer"]:g} per offer. The cost table in the model card shows the share offered moving with the cost.

## Where not to trust it
Any real campaign. The effect, the hidden driver and the economics are all simulated. Top-decile uplift is under-predicted in this run (see the calibration table), so the highest-value customers are the least well estimated.

## Not done
No real data, no multiple offers or doses, no long-run effects, no cost of running the trial, no refit schedule. The decision is a one-off.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
