"""Render the model card and decision memo from results/. No number is typed here.

python -m drift_monitor.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(ci, digits: int = 3) -> str:
    return f"{ci[0]:.{digits}f} to {ci[1]:.{digits}f}"


def _pct(block: dict) -> str:
    return f"{block['rate']:.3f} ({_ci(block['ci95'])})"


def _cell(r: dict) -> str:
    d = r["detection"]["rate"]
    delay = r["median_delay_weeks"]
    return f"{d:.2f} ({'n/a' if delay is None else f'{delay:g}'} wk)"


def render_model_card(metrics: dict, analysis: dict) -> str:
    h, d, res = metrics["headline"], metrics["data"], metrics["results"]
    scenarios = [s for s in config.SCENARIOS if s != "null"]
    header = "| Monitor | Null false alarm | " + " | ".join(scenarios) + " |"
    sep = "|---|---|" + "---|" * len(scenarios)
    rows = "\n".join(
        f"| {m} | {_pct(res[m]['null']['false_alarm'])} | "
        + " | ".join(_cell(res[m][s]) for s in scenarios)
        + " |"
        for m in res
    )
    thr = "\n".join(f"- {m}: {v:.4f}" for m, v in metrics["thresholds"].items())
    dev = ", ".join(f"{m} {v:.3f}" for m, v in metrics["selection"]["dev_mean_detection"].items())
    sweep = "\n".join(
        f"| {r['shift_sd']} | {r['headline']['detection']['rate']:.2f} | "
        f"{r['psi_fixed_0.2']['detection']['rate']:.2f} |"
        for r in analysis["sweep"]
    )
    t = metrics["traps"]
    fx = t["fixed_psi_rule_of_thumb"]
    fx_rows = "\n".join(
        f"| PSI > {k} | {_pct(v['false_alarm_batch_500'])} | {_pct(v['false_alarm_batch_100'])} |"
        for k, v in fx["by_threshold"].items()
    )
    mv, bl = t["threshold_moved_across_batch_size"], t["label_free_blind_to_concept_drift"]
    supp = metrics["supplementary_null_check"]
    supp_rows = "\n".join(f"| {m} | {_pct(v)} |" for m, v in supp["false_alarm"].items())
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    misses = analysis["headline_misses"]
    miss_text = (
        "\n".join(f"- {x['scenario']}: detection {_pct(x['detection'])}" for x in misses)
        or "- none"
    )
    smallest = analysis["smallest_shift_reaching_floor"]
    smallest_text = (
        "no tested shift reached the detection floor"
        if smallest is None
        else f"{smallest} standard deviations"
    )
    return f"""# Model card: drift monitoring

{_banner(metrics)}Generated by `python -m drift_monitor.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for choosing, calibrating, and testing drift monitors against drift whose start is known. Not a production monitoring system.

## Data
Simulated weekly batches of {d["batch_size"]} rows over {d["weeks"]} weeks, drift starting at week {d["onset_week"]}. The monitored model is a logistic regression with reference AUC {d["reference_auc"]:.3f}. {d["calibration_streams"]} null streams set thresholds, {d["dev_streams_per_scenario"]} streams per scenario picked the headline, and {d["test_streams_per_scenario"]} streams per scenario were scored once. See `data/DATA_CARD.md`.

## Design
Each threshold is the {1 - config.BUDGET:.0%} quantile of the weekly maximum of the statistic over null streams, so a null stream has about a {config.BUDGET:.0%} chance of any alarm in {d["weeks"]} weeks. Label-free monitors: psi_max (largest PSI over features), ks_max (largest KS over numeric features), score_psi (PSI of the model score). auc_drop uses labels that arrive {config.LABEL_LAG} weeks late. The psi_fixed rows use PSI cutoffs as commonly quoted, with no calibration.

Thresholds:
{thr}

Headline chosen on dev (mean detection over feature-drift scenarios): {dev}. Headline: **{h["monitor"]}**.

## Results on test streams
Cells show detection rate within {d["weeks"] - d["onset_week"]} weeks of onset, with median delay in weeks (including label lag). The null column is the chance of any alarm in a drift-free stream.

{header}
{sep}
{rows}

Headline abrupt covariate shift detection: {h["value"]:.3f} ({_ci(h["ci95"])}, {h["ci_method"]}).

## How small a shift can it see
One feature shifted by the given number of standard deviations. Smallest tested shift where the headline reaches detection {config.DETECTION_FLOOR}: {smallest_text}.

| Shift (sd) | Headline detection | PSI > 0.2 detection |
|---|---|---|
{sweep}

## The traps, measured
Fixed PSI cutoffs on drift-free streams:

| Rule | False alarm, batch 500 | False alarm, batch 100 |
|---|---|---|
{fx_rows}

- Small shift (0.3 sd): PSI > 0.2 detects {_pct(fx["detection_of_small_shift_psi_0.2"])}; the calibrated headline detects {_pct(fx["detection_of_small_shift_calibrated_headline"])}.
- Calibrated threshold moved across batch size: false alarm {_pct(mv["headline_false_alarm_batch_500"])} at batch 500, {_pct(mv["headline_false_alarm_batch_100"])} at batch 100. {mv["note"]}
- Concept drift: the headline detects {_pct(bl["headline_detection"])}. The delayed-label AUC monitor detects {_pct(bl["delayed_label_auc_detection"])}, median delay {bl["delayed_label_median_delay_weeks"]:g} weeks. {bl["note"]}

## Where it fails
Headline scenarios with detection below 0.5:
{miss_text}

## Follow-up: false alarm rate on {supp["streams"]} fresh null streams
Post hoc. Run after the gate result was known, and not part of the gate.

| Monitor | Stream-level false alarm |
|---|---|
{supp_rows}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    h, gate, t = metrics["headline"], metrics["gate"], metrics["traps"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    supp = metrics["supplementary_null_check"]["false_alarm"][h["monitor"]]
    fx = t["fixed_psi_rule_of_thumb"]["by_threshold"]["0.2"]
    bl = t["label_free_blind_to_concept_drift"]
    outcome = (
        "The monitor passed the pre-set limit."
        if gate["passed"]
        else "The monitor failed on the pre-set limit."
    )
    return f"""# Decision memo: which drift monitor to run weekly

{_banner(metrics)}Generated by `python -m drift_monitor.report` from `results/`. Do not edit by hand.

## The question
Can a team run a label-free drift monitor with a calibrated threshold and trust that it rarely cries wolf and catches a real shift?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline monitor {h["monitor"]}.
{checks}

Stream-level false alarm rate on the test null streams: {_pct(h["false_alarm_rate"])}. Abrupt covariate shift detection: {_pct({"rate": h["value"], "ci95": h["ci95"]})}.

## What the gate result does and does not say
The follow-up on {metrics["supplementary_null_check"]["streams"]} fresh null streams (post hoc, not part of the gate) gives {_pct(supp)} for the headline against a target of {config.BUDGET}. {outcome} A likely reason is calibration noise: thresholds set from {metrics["data"]["calibration_streams"]} null streams leave the achieved false alarm rate off target by more than the gate allows for, and this project did not test that cause. Calibration needs many null streams, and a real team has one reference history, not a thousand simulated years.

## What a wrong call costs
Too many false alarms and the team stops reading the alert. A missed shift means a model degrades unseen. Fixed PSI cutoffs fail both ways: at batch size 100, PSI > 0.2 raised a false alarm in {_pct(fx["false_alarm_batch_100"])} of null streams, and at batch size 500 it missed small shifts the calibrated monitor caught.

## Where not to trust it
Concept drift. The headline detects it in {_pct(bl["headline_detection"])} of streams because the inputs do not move. Only the label-based monitor sees it, after a delay of {bl["delayed_label_median_delay_weeks"]:g} weeks here. A label-free monitor alone is not a performance monitor.

## Not done
No calibration by resampling real reference weeks. No retraining or adaptive reference. No seasonality. No text or image inputs. No real production data.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
