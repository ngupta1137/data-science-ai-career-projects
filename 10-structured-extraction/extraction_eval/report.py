"""Render the model card and decision memo from results/. No number is typed here.

python -m extraction_eval.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _f(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def _ci(block: dict) -> str:
    lo, hi = block["ci95"]
    return f"{block['value']:.3f} ({lo:.3f} to {hi:.3f})"


def render_model_card(metrics: dict, analysis: dict) -> str:
    ex, d, t = metrics["extractors"], metrics["data"], metrics["traps"]
    h = metrics["headline"]["extractor"]
    rows = "\n".join(
        f"| {n} | {_ci(v['seen']['doc_level'])} | {_ci(v['unseen_E']['doc_level'])} | {_ci(v['unseen_G']['doc_level'])} | "
        f"{_ci(v['unseen_pooled']['doc_level'])} | {_f(v['seen']['micro']['f1'])} | {_f(v['unseen_pooled']['micro']['f1'])} |"
        for n, v in ex.items()
    )
    fields = "\n".join(
        f"| {f} | {ex[h]['seen']['fields'][f]['accuracy']['value']:.3f} | {ex[h]['unseen_E']['fields'][f]['accuracy']['value']:.3f} | {ex[h]['unseen_G']['fields'][f]['accuracy']['value']:.3f} |"
        for f in config.FIELDS
    )
    tmpl = "\n".join(
        f"| {tt} | {', '.join(f'{n} {v["seen_by_template"][tt]["value"]:.3f}' for n, v in ex.items())} |"
        for tt in config.SEEN_TEMPLATES
    )
    sil = "\n".join(
        f"| {n} | {v['seen']['wrong_values']} of which {v['seen']['schema_valid_but_wrong']} schema-valid | "
        f"{v['unseen']['wrong_values']} of which {v['unseen']['schema_valid_but_wrong']} schema-valid | "
        f"{t['silent_errors'][n]['abstain_rate_seen']:.3f} | {t['silent_errors'][n]['abstain_rate_unseen']:.3f} |"
        for n, v in ((k, t["silent_errors"][k]) for k in t["silent_errors"])
    )
    ocr_names = list(next(iter(t["ocr_noise"].values())))
    ocr = "\n".join(
        f"| {rate} | " + " | ".join(f"{row[n]:.3f}" for n in ocr_names) + " |"
        for rate, row in t["ocr_noise"].items()
    )
    lto = t["random_split_vs_held_out_template"]
    curve = "\n".join(
        f"| {r['train_docs']} | {r['seen_doc_level']:.3f} | {r['unseen_doc_level']:.3f} |"
        for r in t["labelled_documents_needed"]
    )
    post = analysis["post_hoc_new_template_labels"]
    post_rows = "\n".join(
        f"| {r['template']} | {r['labelled_documents_from_new_template']} | {_ci(r['doc_level'])} |"
        for r in post["rows"]
    )
    tax_e, tax_g = (
        analysis["error_taxonomy"][h]["unseen_E"],
        analysis["error_taxonomy"][h]["unseen_G"],
    )
    fh = t["field_scores_hide_document_errors"]
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    return f"""# Model card: structured extraction from invoices

{_banner(metrics)}Generated by `python -m extraction_eval.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating document field extraction: canonical scoring, document-level accuracy, failure taxonomy, unseen templates and OCR noise. Not a production extractor.

## Data
Generated invoices with five fields (vendor, invoice number, date, total, currency). {d["train"]} train, {d["dev"]} dev and {d["test_seen"]} test documents from seen templates {", ".join(d["seen_templates"])}; {d["test_unseen_per_template"]} test documents from each unseen template {", ".join(d["unseen_templates"])}. See `data/DATA_CARD.md`.

## Extractors
- `first_match`: the first candidate of each type. A baseline.
- `template_regex`: hand-written rules for templates A, B and C, covering label variants that appear in at least 30% of their documents. It returns nothing when no rule matches.
- `span_ranker`: a logistic regression that scores every candidate span from the words around it and its position, trained on the seen templates. It returns nothing when its best score is below {metrics["assumptions"]["abstain_below"]:g}.

## Results
Share of documents with all five fields correct (Wilson 95% intervals), then micro F1 over the five fields.

| Extractor | Seen templates | Unseen E | Unseen G | Unseen pooled | Micro F1 seen | Micro F1 unseen |
|---|---|---|---|---|---|---|
{rows}

Headline: **{h}** ({metrics["headline"]["selected_by"]}).

### Accuracy by field for the headline
| Field | Seen | Unseen E | Unseen G |
|---|---|---|---|
{fields}

### Seen templates, document-level by template
| Template | Extractors |
|---|---|
{tmpl}

## The traps, measured
- Field scores hide document errors: for the headline, micro F1 is {_f(fh["micro_f1_unseen"])} on unseen templates while only {fh["doc_level_unseen"]:.3f} of documents are fully right. On seen templates the two are {_f(fh["micro_f1_seen"])} and {fh["doc_level_seen"]:.3f}.
- Random split versus a held-out template: a random split of documents from seen templates gives {lto["random_split_doc_level_seen"]:.3f}. Training on two templates and testing on the third gives {", ".join(f"{k} {v:.3f}" for k, v in lto["leave_one_template_out"].items())} (mean {lto["mean_leave_one_template_out"]:.3f}). {lto["note"]}
- Silent errors: wrong values that still parse as a valid date, amount or currency pass any schema check.

| Extractor | Wrong values, seen | Wrong values, unseen | Abstain rate, seen | Abstain rate, unseen |
|---|---|---|---|---|
{sil}

### OCR noise
Share of documents fully right when look-alike characters are swapped at the given rate per character. The ceiling column is the share of documents where every true value is still readable as some candidate, so no span extractor can beat it.

| Swap rate | {" | ".join(ocr_names)} |
|---|{"---|" * len(ocr_names)}
{ocr}

### How many labelled documents from seen templates?
| Training documents | Seen | Unseen |
|---|---|---|
{curve}

## Where the headline fails on unseen templates
Template E (new label words): {json.dumps(tax_e)}. Template G (German labels, European number format): {json.dumps(tax_g)}.

## Post hoc: labelled documents from the new template
{post["status"].capitalize()}. Training on the seen templates plus k labelled documents from the new one.

| Template | Labelled documents from it | Documents fully right |
|---|---|---|
{post_rows}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    hd, gate, ex, t = metrics["headline"], metrics["gate"], metrics["extractors"], metrics["traps"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    h = hd["extractor"]
    diff = hd["minus_first_match_seen"]
    sil = t["silent_errors"][h]["unseen"]
    post = [
        r
        for r in analysis["post_hoc_new_template_labels"]["rows"]
        if r["labelled_documents_from_new_template"] > 0
    ]
    small = min(post, key=lambda r: (r["labelled_documents_from_new_template"], r["template"]))
    lto = t["random_split_vs_held_out_template"]
    return f"""# Decision memo: can this extractor process invoices from a new customer's format without review?

{_banner(metrics)}Generated by `python -m extraction_eval.report` from `results/`. Do not edit by hand.

## The question
Can the extractor be switched on for a customer whose invoice layout was not in the training data, with no human checking the output?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline extractor: {h}.
{checks}

Documents fully right on seen templates: {_ci({"value": hd["value"], "ci95": hd["ci95"]})}. On the two unseen templates pooled: {_ci({"value": hd["unseen_value"], "ci95": hd["unseen_ci95"]})}. Against the first-match baseline on seen templates: {diff["value"]:+.3f} ({diff["ci95"][0]:+.3f} to {diff["ci95"][1]:+.3f}).

## Why the seen-template number is not the answer
It is {hd["value"]:.3f}, which looks finished. A random split of documents from templates the model has seen measures how well it memorised those templates. Holding one template out and training on the other two gives a mean of {lto["mean_leave_one_template_out"]:.3f}. The generated documents are also far cleaner than real ones, so even the seen number is an upper bound on what real invoices would give.

## The danger is silent errors, not low accuracy
On unseen templates the headline returned {sil["wrong_values"]} wrong values, and {sil["schema_valid_but_wrong"]} of them are values that pass any schema check. The hand-written rules returned nothing on unseen templates instead of guessing (abstain rate {ex["template_regex"]["unseen_pooled"]["abstain_rate"]:.2f}), which is the safer failure, although they read fewer seen-template documents correctly ({ex["template_regex"]["seen"]["doc_level"]["value"]:.3f} against {ex[h]["seen"]["doc_level"]["value"]:.3f}). A threshold on confidence was set once ({metrics["assumptions"]["abstain_below"]:g}) and not tuned; it did not stop the wrong values.

## What would work
Label a few documents from each new template and retrain. In the post hoc study, {small["labelled_documents_from_new_template"]} labelled documents from template {small["template"]} took the share of fully right documents to {small["doc_level"]["value"]:.3f}. More labelled documents from seen templates did nothing for unseen ones (see the learning curve). Until a template has labels, route its documents to review.

## What a wrong call costs
A wrong total or date that parses is posted to a ledger without anyone seeing it. The cost per error is an assumption this project does not make.

## Where not to trust it
Any template whose label words or layout differ from training. Anything with scan noise: at the highest noise rate no span extractor can recover the ceiling shown in the model card. Anything outside this generator.

## Not done
No LLM extractor, no layout or image model, no line-item extraction, no calibrated confidence, no real invoices. The LLM-with-schema run is designed, not built; the scoring code applies to its output unchanged.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
