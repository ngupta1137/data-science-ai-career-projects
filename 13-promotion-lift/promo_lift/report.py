"""Render the model card and decision memo from results/. No number is typed here.

python -m promo_lift.report
"""

from __future__ import annotations

import json

from . import config


def _banner(m: dict) -> str:
    if m["fast_mode"] or m["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(e: dict) -> str:
    return f"{e['value']:+.1f} ({e['ci95'][0]:+.1f} to {e['ci95'][1]:+.1f})"


def render_model_card(m: dict, a: dict) -> str:
    d, s = m["data"], a["method_study"]["estimators"]
    rows = "\n".join(
        f"| {n} | {_ci(e)} | {e['call']} | {s[n]['bias']:+.1f} | {s[n]['rmse']:.1f} | {s[n]['coverage']:.3f} | "
        f"{s[n]['share_run_it']:.3f} | {s[n]['share_stop_it']:.3f} | {s[n]['share_unclear']:.3f} |"
        for n, e in m["estimators"].items()
    )
    parts = "\n".join(
        f"| {k.replace('_', ' ')} | {v:+.1f} |"
        for k, v in a["true_profit_parts_per_promoted_store"].items()
    )
    seg = "\n".join(
        f"| {r['segment']} | {r['stores']} | {r['promoted_stores']} | {r['estimate']:+.1f} ({r['ci95'][0]:+.1f} to {r['ci95'][1]:+.1f}) | {r['truth']:+.1f} | {r['call']} |"
        for r in a["segments"]
    )
    power = "\n".join(
        f"| {r['stores']} | {r['campaigns']} | {r['share_stop_it']:.3f} | {r['share_unclear']:.3f} | {r['share_run_it']:.3f} | {r['coverage']:.3f} |"
        for r in a["stores_needed"]
    )
    t = m["traps"]
    pk = t["manager_picked_stores"]
    cav = "\n".join(f"- {c}" for c in m["caveats"])
    return f"""# Model card: promotion lift

{_banner(m)}Generated by `python -m promo_lift.report` from `results/`. Do not edit by hand.

## Intended use
Learning. A reference for measuring whether a store promotion made money, and why the usual shortcuts get the sign wrong. Not a promotion planning system.

## Data
One simulated campaign of {d["stores"]} stores ({d["promoted_stores"]} promoted at random) over {d["weeks"]} weeks. Promotion weeks {d["promo_weeks"][0]} to {d["promo_weeks"][-1]}, post weeks {d["post_weeks"][0]} to {d["post_weeks"][-1]}, comparison weeks {d["pre_weeks"][0]} to {d["pre_weeks"][-1]}. See `data/DATA_CARD.md`.

## Assumptions
Margin {m["assumptions"]["margin_item"]:g} per unit on the promoted item, discount {m["assumptions"]["discount"]:g} per promoted unit, margin {m["assumptions"]["margin_sibling"]:g} on the sibling. All are assumptions.

## Estimates against the truth
True incremental profit per promoted store on this campaign: **{m["true_incremental_profit_per_promoted_store"]:+.1f}**. The method study columns come from {a["method_study"]["campaigns"]} simulated campaigns of the same design.

| Estimator | This campaign (95% interval) | Call | Bias | RMSE | Coverage | Share run it | Share stop it | Share unclear |
|---|---|---|---|---|---|---|---|---|
{rows}

- `pre_post`: promoted stores only, promoted item only, promotion weeks against the weeks before.
- `window_did`: adds control stores, still promoted item and promotion weeks only.
- `full_did`: control stores, promoted item and sibling, promotion and post weeks. Headline, fixed before results.

## Where the profit goes
True parts of the incremental profit per promoted store. They sum to the truth. Extra units sold: {t["units_up_profit_down"]["extra_units_per_promoted_store"]:.0f} per promoted store.

| Part | Profit per promoted store |
|---|---|
{parts}

## The traps, measured
- Before and after without control stores: estimate {t["before_and_after_without_control"]["headline_estimate"]:+.1f}, bias {t["before_and_after_without_control"]["bias_over_campaigns"]:+.1f} over campaigns. {t["before_and_after_without_control"]["note"]}
- Counting only the promoted item in promotion weeks: estimate {t["counting_only_the_promoted_item_in_promo_weeks"]["headline_estimate"]:+.1f}, bias {t["counting_only_the_promoted_item_in_promo_weeks"]["bias_over_campaigns"]:+.1f}. It misses cannibalisation ({t["counting_only_the_promoted_item_in_promo_weeks"]["missed_cannibalisation"]:+.1f}) and pull-forward ({t["counting_only_the_promoted_item_in_promo_weeks"]["missed_pull_forward"]:+.1f}).
- Manager-picked stores: full difference-in-differences has bias {pk["bias_full_did_random"]:+.1f} with random stores and {pk["bias_full_did_picked"]:+.1f} when the best-trending stores are picked, with coverage {pk["coverage_picked"]:.3f}. {pk["note"]}

## By store type (headline estimator)
| Segment | Stores | Promoted | Estimate (95% interval) | Truth | Call |
|---|---|---|---|---|---|
{seg}

## How many stores?
Full difference-in-differences over repeated campaigns.

| Stores | Campaigns | Share stop it | Share unclear | Share run it | Coverage |
|---|---|---|---|---|---|
{power}

## Limits
{cav}

## Versions
Seed {m["seed"]}. Python {m["versions"]["python"]}, numpy {m["versions"]["numpy"]}, scipy {m["versions"]["scipy"]}.
"""


def render_decision_memo(m: dict, a: dict) -> str:
    g, h, e = m["gate"], m["headline"], m["estimators"]
    s = a["method_study"]["estimators"]["full_did"]
    checks = "\n".join(f"- {k}: {v}" for k, v in g["checks"].items())
    worst = min(a["segments"], key=lambda r: r["truth"])
    p200 = next(
        (r for r in a["stores_needed"] if r["stores"] == m["data"]["stores"]),
        a["stores_needed"][-1],
    )
    return f"""# Decision memo: did the promotion make money?

{_banner(m)}Generated by `python -m promo_lift.report` from `results/`. Do not edit by hand.

## The question
Run this promotion again, or stop it?

## The rule, set before results were seen
{g["rule"]}

## The call: {"PASS" if g["passed"] else "FAIL"}
{checks}

Incremental profit per promoted store: {_ci(h)}. Recommendation from the headline method: **{h["call"]}**. True value: {m["true_incremental_profit_per_promoted_store"]:+.1f}.

## Why the shortcuts disagree
A before-and-after view says {e["pre_post"]["value"]:+.1f} ({e["pre_post"]["call"]}). Adding control stores but counting only the promoted item in promotion weeks says {e["window_did"]["value"]:+.1f} ({e["window_did"]["call"]}). Units went up, but the discount is paid on every unit, including those that would have sold anyway, and some sales came from the sibling item or from later weeks.

## Where this is fragile
- With {p200["stores"]} stores the right method gave a definite answer in {1 - p200["share_unclear"]:.0%} of simulated campaigns and was unclear in the rest. This campaign happened to be definite. The store-count table in the model card shows how more stores help.
- Its interval covered the truth in {s["coverage"]:.1%} of campaigns, close to the 95% it claims.
- If the stores are picked by a manager rather than at random, the same method is badly biased. See the model card.
- By store type the intervals are wide. The {worst["segment"]} stores lose the most in truth ({worst["truth"]:+.1f}).

## What a wrong call costs
Running a loss-making promotion again repeats the loss in every promoted store. Stopping a profitable one gives up its profit. Both sizes depend on margins and discount, which are assumptions here.

## Not done
No supplier funding, no halo on other categories, no competitor response, no stock-outs, no repeated promotions or long-run price perception.
"""


def main() -> None:
    m = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    a = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(render_model_card(m, a), encoding="utf-8")
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(m, a), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
