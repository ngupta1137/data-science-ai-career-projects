"""Render the model card and decision memo from results/. No number is typed here.

python -m oos_detect.report
"""

from __future__ import annotations

import json

from . import config


def _banner(m: dict) -> str:
    if m["fast_mode"] or m["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(e: dict, d: int = 2) -> str:
    return f"{e['value']:+.{d}f} ({e['ci95'][0]:+.{d}f} to {e['ci95'][1]:+.{d}f})"


def _n(x, d: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{d}f}"


def render_model_card(m: dict, a: dict) -> str:
    d, asm, t = m["data"], m["assumptions"], m["traps"]
    rows = "\n".join(
        f"| {p} | {_ci(r['net_value_per_store_day'])} | {r['lost_margin_per_store_day']:.2f} | {r['visits_per_day']:.1f} | "
        f"{r['flagged_per_day']:.0f} | {_n(r['precision'])} | {_n(r['recall'])} | {_n(r['median_days_to_fix'], 0)} |"
        for p, r in m["policies"].items()
    )
    bands = "\n".join(
        f"| {b['band']} | {b['share_of_shelves']:.3f} | {b['share_of_lost_margin_with_no_visits']:.3f} | "
        + " | ".join(
            f"{b[p]['share_of_visits']:.3f} / {_n(b[p]['precision'])} / {b[p]['share_of_lost_margin_recovered']:.3f}"
            for p in ("zero_run_rule", "expected_value", "oracle")
        )
        + " |"
        for b in a["demand_bands"]
    )
    cap = "\n".join(
        f"| {r['capacity_per_day']} | {r['zero_run_rule']['net_value_per_store_day']:+.2f} | {r['expected_value']['net_value_per_store_day']:+.2f} | "
        f"{_n(r['expected_value']['precision'])} | {_n(r['expected_value']['recall'])} |"
        for r in a["capacity"]
    )
    ph = a["post_hoc_visit_calibration"]
    cal = "\n".join(
        f"| {r['fifth_of_visits_by_predicted_chance']} | {r['visits']} | {r['mean_predicted_chance_empty']:.3f} | {r['share_found_empty']:.3f} |"
        for r in ph["rows"]
    )
    z, s, al = (
        t["zero_sales_read_as_zero_demand"],
        t["same_rule_for_every_shelf"],
        t["alarm_without_value"],
    )
    cav = "\n".join(f"- {c}" for c in m["caveats"])
    return f"""# Model card: out-of-stock detection

{_banner(m)}Generated by `python -m oos_detect.report` from `results/`. Do not edit by hand.

## Intended use
Learning. A reference for turning point-of-sale data into a short daily list of shelves to check, under a fixed visit budget. Not a store operations system.

## Data
{d["stores"]} simulated stores, {d["shelves"]} shelves, {d["history_days"]} history days without visits and {d["eval_days"]} evaluation days. With no visits, {d["eval_empty_episodes"]} empty-shelf episodes start in the evaluation days. See `data/DATA_CARD.md`.

## Assumptions
Margin {asm["margin"]:g} per unit, visit cost {asm["visit_cost"]:g}, {asm["capacity_per_day"]} visits a day across the chain, prior share of empty shelves {asm["prior_empty"]:g}. All are assumptions. Every policy faces the same demand and the same empty-shelf episodes.

## Policies
Net value is margin saved over no visits minus visit cost, per store per day, with a store-bootstrap 95% interval.

| Policy | Net value per store per day | Lost margin per store per day | Visits per day | Shelves flagged per day | Precision | Recall | Median days to fix |
|---|---|---|---|---|---|---|---|
{rows}

- `zero_run_rule`: flag after {asm["zero_run_rule_days"]} days with no sales, longest gap first.
- `poisson_alarm`: flag when the gap is very unlikely for the shelf's rate.
- `expected_value`: chance the shelf is empty times the margin it would lose, visited if that beats the visit cost. Headline, fixed before results.
- `expected_value_naive_rate`: the same with the rate estimated from all history days.
- `oracle`: knows which shelves are empty. Upper bound.

## By sales rate
Each cell: share of the policy's visits / precision / share of lost margin recovered.

| Band | Share of shelves | Share of lost margin, no visits | Zero-day rule | Expected value | Oracle |
|---|---|---|---|---|---|
{bands}

## Visit budget
| Visits per day | Net value, zero-day rule | Net value, expected value | Precision, expected value | Recall, expected value |
|---|---|---|---|---|
{cap}

## The traps, measured
- Zero sales read as zero demand: median naive rate is {z["median_ratio_naive_to_true"]:.3f} of the true rate and the corrected rate is {z["median_ratio_clean_to_true"]:.3f}. Net value {z["net_value_naive_rate"]:+.2f} with the naive rate and {z["net_value_clean_rate"]:+.2f} with the corrected one. In this simulation the bias is small and the correction overshoots.
- One rule for every shelf: the zero-day rule flags {s["zero_run_rule_flagged_per_day"]:.0f} shelves a day against {s["capacity_per_day"]} visits, with precision {s["zero_run_rule_precision"]:.3f}. {s["note"]}
- Alarm without value: the alarm has precision {al["poisson_alarm_precision"]:.3f} and net value {al["poisson_alarm_net_value"]:+.2f}. {al["note"]}

## Post hoc: is the chance of an empty shelf right?
{ph["status"].capitalize()}. Mean predicted chance on visited shelves {ph["mean_predicted_chance_empty"]:.3f}; share found empty {ph["share_found_empty"]:.3f}. During evaluation {ph["share_of_shelf_days_truly_empty_during_evaluation"]:.3f} of shelf-days were empty, against a prior of {asm["prior_empty"]:g}.

| Fifth of visits | Visits | Mean predicted chance | Share found empty |
|---|---|---|---|
{cal}

Fifths are uneven where many shelves share a predicted chance.

## Limits
{cav}

## Versions
Seed {m["seed"]}. Python {m["versions"]["python"]}, numpy {m["versions"]["numpy"]}, scipy {m["versions"]["scipy"]}.
"""


def render_decision_memo(m: dict, a: dict) -> str:
    g, h, p = m["gate"], m["headline"], m["policies"]
    checks = "\n".join(f"- {k}: {v}" for k, v in g["checks"].items())
    best = max(
        (k for k in p if k != "oracle"), key=lambda k: p[k]["net_value_per_store_day"]["value"]
    )
    cap = a["capacity"]
    lo = min(cap, key=lambda r: r["capacity_per_day"])
    ph = a["post_hoc_visit_calibration"]
    z = m["traps"]["zero_sales_read_as_zero_demand"]
    return f"""# Decision memo: can the daily shelf-check list go live?

{_banner(m)}Generated by `python -m oos_detect.report` from `results/`. Do not edit by hand.

## The question
Replace the three-days-without-a-sale rule with a value-ranked list of shelves to check?

## The rule, set before results were seen
{g["rule"]}

## The call: {"PASS" if g["passed"] else "FAIL"}
{checks}

Net value per store per day {_ci(h)} over no visits, and {_ci(h["minus_zero_run_rule"])} over the zero-day rule. Precision {h["precision"]:.3f}.

## What this means
The value-ranked list earns more than the current rule, which loses money at this budget. It fails the precision check: most visits find a full shelf. By point estimate the best non-oracle policy here was `{best}`, though the intervals of the three value-aware policies overlap, and the oracle shows {p["oracle"]["net_value_per_store_day"]["value"]:+.2f} is available.

## Why it fails
The model is overconfident. Visited shelves had a predicted chance of being empty of {ph["mean_predicted_chance_empty"]:.3f}, and {ph["share_found_empty"]:.3f} were. Two measured facts point the same way: the corrected sales rate runs high (median {z["median_ratio_clean_to_true"]:.3f} of the truth), and the prior of {m["assumptions"]["prior_empty"]:g} is above the {ph["share_of_shelf_days_truly_empty_during_evaluation"]:.3f} share of shelf-days that were empty once visits began. How much each contributes was not measured, and ranking thousands of flagged shelves by a noisy score may add a winner's curse on top. The budget table agrees: at {lo["capacity_per_day"]} visits a day the same policy earns {lo["expected_value"]["net_value_per_store_day"]:+.2f}, so the marginal visits at the full budget lose money even though the model says they pay.

## What to do next
Calibrate the chance of an empty shelf on audited visits before trusting the visit-cost cut-off, lower the prior as visits clear shelves, and cap visits until the calibration holds. Then rerun this gate unchanged.

## What a wrong call costs
A wasted visit costs {m["assumptions"]["visit_cost"]:g}. A missed empty shelf costs its daily margin until someone notices. Both are assumptions here.

## Not done
No weekday or promotion effects, no back-room stock, no rep misses, no shelf audits to calibrate against.
"""


def main() -> None:
    m = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    a = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(render_model_card(m, a), encoding="utf-8")
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(m, a), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
