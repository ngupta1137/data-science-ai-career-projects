"""Render the model card and decision memo from results/. No number is typed here.

python -m credit_score.report
"""

from __future__ import annotations

import json

from . import config


def _banner(m: dict) -> str:
    if m["fast_mode"] or m["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(e: dict, d: int = 4) -> str:
    return f"{e['value']:+.{d}f} ({e['ci95'][0]:+.{d}f} to {e['ci95'][1]:+.{d}f})"


def _n(x, d: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{d}f}"


def render_model_card(m: dict, a: dict) -> str:
    d, t = m["data"], m["traps"]
    rows = "\n".join(
        f"| {n} | {r['approval_rate']:.3f} | {_n(r['default_rate_approved'])} | {_ci(r['profit_per_applicant'])} | "
        f"{_n(r.get('gini_all_applicants'))} | {_n(r.get('gini_old_approved_only'))} | {_n(r.get('calibration_approved'))} | "
        f"{_n(r.get('calibration_old_approved'))} | {_n(r.get('calibration_old_declined'))} |"
        for n, r in m["models"].items()
    )
    size = "\n".join(
        f"| {r['random_share']:.0%} | {r['random_loans']} | {r['replications']} | {r['mean_profit_per_applicant']:.4f} | {r['min_profit_per_applicant']:.4f} | "
        f"{r['mean_calibration_approved']:.3f} | {r['worst_calibration_approved']:.3f} |"
        for r in a["random_sample_size"]
    )
    dec = "\n".join(
        f"| {i + 1} | " + " | ".join(f"{r['rows'][i]['mean_predicted']:.3f} / {r['rows'][i]['true_rate']:.3f}" for r in a["calibration_by_decile"]) + " |"
        for i in range(10)
    )
    names = " | ".join(r["model"] for r in a["calibration_by_decile"])
    ev, wt, sm, co = t["evaluate_on_approved_only"], t["weighting_cannot_fix_what_was_not_recorded"], t["small_unbiased_sample"], t["cost_of_learning"]
    cav = "\n".join(f"- {c}" for c in m["caveats"])
    return f"""# Model card: credit scorecard with reject bias

{_banner(m)}Generated by `python -m credit_score.report` from `results/`. Do not edit by hand.

## Intended use
Learning. A reference for building a default model when outcomes are seen only for loans you approved, and for deciding whether it should replace the current policy. Not a lending system and not a regulatory method.

## Data
{d["history"]} simulated past applications, {d["history_approved"]} approved (including {d["history_random_approved"]} approved at random). {d["test"]} fresh applications where every outcome is known; the true default rate among all of them is {d["test_default_rate_all"]:.3f} and the old policy approves {d["test_old_approval_rate"]:.3f}. See `data/DATA_CARD.md`.

## Assumptions
Margin {m["assumptions"]["margin"]:g} on a repaid loan, loss {m["assumptions"]["loss"]:g} on a default, so a loan is approved when the predicted default chance is below {m["assumptions"]["approve_below"]:.3f}. Assumptions.

## Models and policies on fresh applicants
Profit is per applicant, with a bootstrap 95% interval. Gini on all applicants needs the simulator; Gini on old-approved applicants is what a lender can check. Calibration is mean predicted default chance over the true rate.

| Model or policy | Approval rate | Default rate of approved | Profit per applicant | Gini, all | Gini, old-approved only | Calibration, own approvals | Calibration, old-approved | Calibration, old-declined |
|---|---|---|---|---|---|---|---|---|
{rows}

- `accepted_only`: gradient boosting on approved loans.
- `ipw`: the same, weighted by one over the chance of approval given recorded features.
- `random_sample_only`: logistic regression on the loans approved at random.
- `recalibrated`: accepted-only scores, recalibrated on the random sample. Headline, fixed before results.

## The traps, measured
- Evaluating on approved loans only: Gini {ev["gini_old_approved_only"]:.3f} on old-approved applicants against {ev["gini_all_applicants"]:.3f} on all. Calibration {ev["calibration_old_approved"]:.3f} on old-approved and {ev["calibration_old_declined"]:.3f} on old-declined. {ev["note"]}
- Weighting cannot fix what was not recorded: calibration on old-declined applicants is {wt["calibration_old_declined_accepted_only"]:.3f} for accepted-only, {wt["calibration_old_declined_ipw"]:.3f} with weighting and {wt["calibration_old_declined_recalibrated"]:.3f} after recalibration. {wt["note"]}
- A small unbiased sample: Gini {sm["random_sample_only_gini"]:.3f} on the random sample alone against {sm["recalibrated_gini"]:.3f} recalibrated. {sm["note"]}
- The cost of learning: {co["of_which_old_policy_declined"]} of the {co["random_approvals_in_history"]} random approvals were applicants the old policy declined. Their default rate was {co["default_rate_of_those"]:.3f} and they earned {co["profit_on_those_per_loan"]:+.3f} per loan, a cost of {co["cost_per_history_applicant"]:.4f} per past applicant.

## How big a random sample?
The recalibrated model with different random-approval shares, each repeated.

| Random share | Random loans | Replications | Mean profit per applicant | Lowest | Mean calibration, own approvals | Worst |
|---|---|---|---|---|---|---|
{size}

## Calibration by decile, all fresh applicants
Each cell: mean predicted / true default rate.

| Decile | {names} |
|---|{"---|" * len(a["calibration_by_decile"])}
{dec}

## Limits
{cav}

## Versions
Seed {m["seed"]}. Python {m["versions"]["python"]}, numpy {m["versions"]["numpy"]}, scikit-learn {m["versions"]["scikit-learn"]}.
"""


def render_decision_memo(m: dict, a: dict) -> str:
    g, h, t = m["gate"], m["headline"], m["models"]
    checks = "\n".join(f"- {k}: {v}" for k, v in g["checks"].items())
    best = max((k for k in config.MODELS), key=lambda k: t[k]["profit_per_applicant"]["value"])
    return f"""# Decision memo: replace the approval policy with the new scorecard?

{_banner(m)}Generated by `python -m credit_score.report` from `results/`. Do not edit by hand.

## The question
Approve loans with a model built on past data instead of the current policy?

## The rule, set before results were seen
{g["rule"]}

## The call: {"PASS" if g["passed"] else "FAIL"}
{checks}

Profit per applicant {_ci(h)}. Against the old policy {_ci(h["minus_old_policy"])}; against the accepted-only model {_ci(h["minus_accepted_only"])}. Calibration on its own approvals {h["calibration_approved"]:.3f}.

## What this means
Recalibrating on the random sample beats the naive model and brings the predicted default rate within the band, but it does not beat the policy it would replace. In this simulation the old policy used a trait the underwriter saw and the data never recorded. A model on recorded features cannot recover that, so replacing judgement with the model gives that information away. The oracle earns {t["oracle"]["profit_per_applicant"]["value"]:+.4f} per applicant, so better decisions exist; they need better data, not a better fit. By point estimate the best model here was `{best}`.

## What would change the call
Recording what the underwriter used, or adding the model to the current policy rather than replacing it. Neither was tested here. A larger random sample improved calibration in the sample-size table, at a cost the model card prices.

## What a wrong call costs
Approving on an under-predicted default chance books loans that lose {m["assumptions"]["loss"]:g} each when they default. Declining good applicants gives up {m["assumptions"]["margin"]:g} each. Both are assumptions.

## Not done
No risk-based pricing, no economic cycle, no fair-lending analysis, no combination of model and judgement.
"""


def main() -> None:
    m = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    a = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(render_model_card(m, a), encoding="utf-8")
    (config.REPORTS_DIR / "decision_memo.md").write_text(render_decision_memo(m, a), encoding="utf-8")
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
