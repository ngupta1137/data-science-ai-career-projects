"""Render the model card and decision memo from results/. No number is typed here.

python -m llm_judge_eval.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(block: dict) -> str:
    lo, hi = block["ci95"]
    return f"{block['value']:.3f} ({lo:.3f} to {hi:.3f})"


def render_model_card(metrics: dict, analysis: dict) -> str:
    a, c, tri = metrics["assumptions"], metrics["candidates"], metrics["triage"]
    rows = "\n".join(
        f"| {n} | {_ci(v['agreement_consensus'])} | {_ci(v['agreement_truth'])} | {v['kappa_vs_consensus']:.3f} |"
        for n, v in c.items()
    )
    b = metrics["bias"]
    bias_rows = "\n".join(
        f"| {name} | {b['planted'][key]:.2f} | "
        f"{b['recovered_with_true_quality'][key]['value']:.2f} "
        f"({b['recovered_with_true_quality'][key]['ci95'][0]:.2f} to {b['recovered_with_true_quality'][key]['ci95'][1]:.2f}) | "
        f"{b['recovered_with_human_label_as_quality'][key]['value']:.2f} "
        f"({b['recovered_with_human_label_as_quality'][key]['ci95'][0]:.2f} to {b['recovered_with_human_label_as_quality'][key]['ci95'][1]:.2f}) |"
        for name, key in (
            ("Slot bias (logit for first slot)", "position"),
            ("Quality slope", "quality_slope"),
            ("Length slope (per sd)", "length_slope"),
        )
    )
    t = metrics["traps"]
    ceil, fx, sz = t["human_label_is_not_truth"], t["fixed_slot_evaluation"], t["eval_set_size"]
    conf = "\n".join(
        f"| {k} | {_ci(v['swap_coin'])} | {_ci(v['length_only'])} | {_ci(v['oracle'])} |"
        for k, v in t["length_confounded_eval_set"]["by_length_quality_correlation"].items()
    )
    sys_rows = "\n".join(
        f"| {d} | {' > '.join(v['order'])} | {v['v_win_rate_vs']['S4']:.3f} | {v['v_win_rate_vs']['S5']:.3f} | "
        f"{v['share_of_resamples_v_beats']['S4']:.3f} | {v['share_of_resamples_v_beats']['S5']:.3f} |"
        for d, v in t["verbose_system_over_ranked"].items()
    )
    sweep_rows = "\n".join(
        f"| {r['pos_bias']:g} | {r['length_bias']:g} | {r['agreement']['single_order']:.3f} | "
        f"{r['agreement']['swap_coin']:.3f} | {r['agreement']['swap_calibrated']:.3f} | "
        f"{r['v_win_rate_vs_s4_swap_coin']:.3f} | {r['v_win_rate_vs_s4_calibrated']:.3f} |"
        for r in analysis["sweep"]
    )
    band_rows = "\n".join(
        f"| {r['band']} | {r['pairs']} | {r['headline_agreement_truth']:.3f} | "
        f"{r['headline_agreement_consensus']:.3f} | {r['consensus_agreement_truth']:.3f} | {r['split_verdict_rate']:.3f} |"
        for r in analysis["by_quality_gap"]
    )
    dis = analysis["disagreements_with_consensus"]
    pull = analysis["raw_judge_follows_longer_answer"]["single_order_call_picks_longer"]
    needed = sz["n_needed_for_lower_bound_to_reach_floor"]
    needed_txt = (
        f"{needed} labelled pairs"
        if needed
        else "no number of pairs, because the observed agreement is below the floor"
    )
    caveats = "\n".join(f"- {x}" for x in metrics["caveats"])
    sizes = ", ".join(f"n={k}: {v:.3f}" for k, v in sz["wilson_lower_bound_by_n"].items())
    return f"""# Model card: pairwise LLM judge audit

{_banner(metrics)}Generated by `python -m llm_judge_eval.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for auditing a pairwise LLM judge against human labels: measure agreement, find slot and length bias, test mitigations, and see how a biased judge mis-ranks systems. It does not call any model.

## Data
Simulated answer pairs with known true quality ({metrics["data"]["dev_pairs"]} dev, {metrics["data"]["test_pairs"]} test), each judged by {metrics["data"]["annotators"]} simulated annotators and by a simulated judge called in both orders. See `data/DATA_CARD.md`.

## Assumptions
Planted judge: quality slope {a["judge_beta"]:g}, slot bias {a["position_bias"]:g} logits, length bias {a["length_bias"]:g} logits per sd. Humans: quality slope {a["human_beta"]:g}, no slot or length bias. Length tracks quality with correlation {a["length_quality_corr"]:g}. Agreement floor {a["agreement_floor"]:g}. All are assumptions about a made-up judge.

## Agreement on the test set
Wilson 95% intervals. "Truth" is the true quality order, which only a simulation knows. Kappa is against the human consensus.

| Judge | Agreement with human consensus | Agreement with truth | Kappa |
|---|---|---|---|
{rows}

Headline: **{metrics["headline"]["judge"]}** ({metrics["headline"]["selected_by"]}). `swap_coin` calls both orders and breaks splits by a coin; it matches `single_order` in expectation because the coin discards the split. `oracle` is a perfect judge and shows the ceiling: it agrees with the consensus only {ceil["oracle_agreement_with_consensus"]["value"]:.3f} of the time because the consensus itself errs.

## Triage: send split verdicts to humans
Call both orders. Keep the verdict where they agree, send the rest to humans. The judge keeps {tri["coverage"]:.3f} of pairs. On those, agreement with the consensus is {_ci(tri["agreement_consensus_on_decided"])} and with truth {_ci(tri["agreement_truth_on_decided"])}. On the split pairs a single verdict would match the consensus {_ci(tri["agreement_consensus_on_split"])} of the time, which is a coin flip.

## Bias recovery
Logistic fit of "judge picked the first slot", intervals by resampling pairs ({config.N_BOOT_REG} resamples in a full run).

| Bias | Planted | Recovered with true quality | Recovered with human label as quality |
|---|---|---|---|
{bias_rows}

{b["note"]} Share of all calls that picked the first slot: {b["p_first_slot_picked"]:.3f}. Share that picked the longer answer: {pull:.3f}.

## The traps, measured
- A human label is not truth: a single annotator matches the true order {ceil["single_annotator_agreement_with_truth"]:.3f} of the time and the 3-way consensus {ceil["consensus_agreement_with_truth"]["value"]:.3f}. {ceil["note"]}
- Fixed slot: agreement is {fx["agreement_when_consensus_winner_always_first"]["value"]:.3f} when the human-preferred answer always sits first, against {fx["agreement_when_slots_balanced"]["value"]:.3f} with balanced slots. {fx["note"]}
- Eval set size: Wilson lower bound at the headline agreement is {sizes}. Reaching the {a["agreement_floor"]:g} floor needs {needed_txt}.

### Length-confounded evaluation sets
Agreement with the human consensus for the raw swap judge, always picking the longer answer, and a perfect judge, on fresh sets with different length-quality correlation.

| Correlation of length with quality | swap_coin | length_only | oracle |
|---|---|---|---|
{conf}

## System ranking
Six systems, round robin, {config.SYSTEM_N} prompts per pair. V is verbose (1.5 sd longer) with true quality between S3 and S4. The true order is {" > ".join(analysis["systems"]["order_by_truth"])}. Columns give V's head-to-head win rate against S4 and S5 (both truly better, so a fair judge gives under 0.5) and the share of bootstrap resamples in which V beats them.

| Judge | Order by judge | V vs S4 | V vs S5 | Share V beats S4 | Share V beats S5 |
|---|---|---|---|---|---|
{sys_rows}

## Where the headline judge errs
| Quality gap between answers | Pairs | Agreement with truth | Agreement with consensus | Consensus agreement with truth | Split verdict rate |
|---|---|---|---|---|---|
{band_rows}

The headline judge disagrees with the consensus on {dis["count"]} pairs. On {dis["share_where_judge_matches_truth"]:.3f} of them the judge still matched the true order. Calibrator weights: swap score {analysis["calibrator"]["swap_score_weight"]:.2f}, length {analysis["calibrator"]["length_weight"]:.3f}.

## Sensitivity to the planted biases
Mean over {analysis["sweep"][0]["replications"]} replications per cell. Not part of the gate. The last two columns are V's head-to-head win rate against S4 (true value below 0.5).

| Slot bias | Length bias | single_order | swap_coin | swap_calibrated | V vs S4, swap_coin | V vs S4, swap_calibrated |
|---|---|---|---|---|---|---|
{sweep_rows}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    h, gate, c, tri = metrics["headline"], metrics["gate"], metrics["candidates"], metrics["triage"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    dev = analysis["dev_agreement"]
    other = next(k for k in config.CANDIDATES if k != h["judge"])
    diff = h["minus_longer_answer_baseline"]
    sysd = metrics["traps"]["verbose_system_over_ranked"]
    return f"""# Decision memo: can this judge replace human labels for ranking systems?

{_banner(metrics)}Generated by `python -m llm_judge_eval.report` from `results/`. Do not edit by hand.

## The question
Can a pairwise LLM judge be used in place of human preference labels to rank candidate systems, and if not, how should it be used?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline judge: {h["judge"]}.
{checks}

Agreement with the human consensus on test: {h["value"]:.3f}, 95% interval {h["ci95"][0]:.3f} to {h["ci95"][1]:.3f}. Against always picking the longer answer: {diff["value"]:+.3f} ({diff["ci95"][0]:+.3f} to {diff["ci95"][1]:+.3f}). In the system ranking, V beats a truly better system in {h["max_share_v_beats_better_system"]:.3f} of resamples.

## How the headline was chosen, and what that missed
Dev agreement was {dev[h["judge"]]:.4f} for {h["judge"]} and {dev[other]:.4f} for {other}. The rule picks the higher and breaks ties by list order. On test, {other} scored {c[other]["agreement_consensus"]["value"]:.3f} against {c[h["judge"]]["agreement_consensus"]["value"]:.3f}. Choosing between two judges whose dev scores differ by less than the noise is a coin flip, and the rule was not changed after seeing this.

## What would actually work
Call both orders and keep only the verdicts that agree. That keeps {tri["coverage"]:.3f} of pairs at {tri["agreement_consensus_on_decided"]["value"]:.3f} agreement with the consensus (interval {tri["agreement_consensus_on_decided"]["ci95"][0]:.3f} to {tri["agreement_consensus_on_decided"]["ci95"][1]:.3f}). The rest go to humans. Breaking splits with a coin does not help: it has the same expected agreement as one call. The cost of triage is the human labelling of {1 - tri["coverage"]:.3f} of pairs.

## What a wrong call costs
The risk is shipping the wrong system. Under the single-call judge, the verbose system V ranks {sysd["single_order"]["order"].index("V") + 1} of 6 while its true rank is {analysis["systems"]["order_by_truth"].index("V") + 1}. Under always-pick-longer it ranks {sysd["length_only"]["order"].index("V") + 1}. Neither cost can be priced here, because the cost of shipping a worse system is an assumption.

## Where not to trust it
Pairs where the two answers are close in quality: the headline judge agrees with truth {analysis["by_quality_gap"][0]["headline_agreement_truth"]:.3f} of the time there, and the consensus itself only {analysis["by_quality_gap"][0]["consensus_agreement_truth"]:.3f}. No agreement number can be certified on those pairs. Also anything outside this simulation: the judge, the humans and the biases are all planted.

## Not done
No real model was called. No self-preference test. No human length preference. No pointwise or rubric judging. The real-model run is designed, not built: export judge calls in the format described in `llm_judge_eval/audit.py` and run the audit.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
