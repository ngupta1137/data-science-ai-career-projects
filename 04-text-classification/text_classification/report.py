"""Render the model card and decision memo from results/. No number is typed here.

python -m text_classification.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != "newsgroups_sklearn":
        return "> **Not a release result.** Generated from a fast or synthetic run. Do not cite these numbers.\n\n"
    return ""


def _fmt_ci(ci) -> str:
    return (
        "not applicable (headline is Naive Bayes)" if ci is None else f"{ci[0]:.4f} to {ci[1]:.4f}"
    )


def render_model_card(metrics: dict, analysis: dict) -> str:
    head, split, traps = metrics["headline"], metrics["split"], metrics["traps"]
    rows = "\n".join(
        f"| {n} | {r['val_macro_f1']:.4f} | {r['test_accuracy']:.4f} | {r['test_macro_f1']:.4f} |"
        for n, r in metrics["models"].items()
    )
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    mt, vt = traps["metadata_kept"], traps["vectorizer_fit_on_test"]
    pairs = "\n".join(
        f"- {p['true']} predicted as {p['predicted']}: {p['count']} documents"
        for p in analysis["top_confused_pairs"][:5]
    )
    weakest = ", ".join(f"{w['class']} ({w['f1']:.3f})" for w in analysis["weakest_five_classes"])
    sample_class = next(iter(mt["top_features_metadata_kept"]))
    sample_tokens = ", ".join(mt["top_features_metadata_kept"][sample_class])
    return f"""# Model card: text classification

{_banner(metrics)}Generated by `python -m text_classification.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating a multi-class text classifier and for spotting shortcut features. Not for moderating or routing real messages.

## Data
{metrics["data"]["classes"]} newsgroups, {metrics["data"]["rows"]:,} posts. See `data/DATA_CARD.md`.

## Split
Fit {split["fit_rows"]:,} posts, validation {split["val_rows"]:,} (stratified share of the training set, used to choose the model), test {split["test_rows"]:,} ({split["test_selection"]}).

## Results
Macro-F1 is the unweighted mean of per-class F1.

| Model | Val macro-F1 | Test accuracy | Test macro-F1 |
|---|---|---|---|
{rows}

Headline: **{head["model"]}**, chosen by validation macro-F1. Test macro-F1 {head["value"]:.4f}, 95% interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f} ({head["ci_method"]}). Majority baseline {metrics["baseline"]["test_macro_f1"]:.4f}. Gain over Naive Bayes, 95% interval: {_fmt_ci(metrics["gain_over_naive_bayes_ci95"])}.

## The traps, measured
- Metadata kept: test macro-F1 {mt["test_macro_f1_metadata_kept"]:.4f} with headers, footers, and quotes versus {mt["test_macro_f1_metadata_removed"]:.4f} without ({mt["difference"]:+.4f}). {mt["share_of_top_features_absent_from_clean_vocabulary"]:.1%} of the model's top features never appear in the cleaned text. Top tokens for {sample_class}: {sample_tokens}. {mt["note"]}
- Vectorizer fitted on test text: {vt["test_macro_f1_vectorizer_fit_on_test"]:.4f} versus {vt["test_macro_f1_honest"]:.4f} honest ({vt["difference"]:+.4f}). {vt["note"]}

## Where it fails
Weakest classes by F1: {weakest}. Most confused pairs:
{pairs}

Empty documents after cleaning: {analysis["empty_documents"]["n"]} ({analysis["empty_documents"]["share"]:.1%} of test). Full tables are in `results/error_analysis.json`.

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, scikit-learn {metrics["versions"]["scikit-learn"]}, pandas {metrics["versions"]["pandas"]}, numpy {metrics["versions"]["numpy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    head, gate, mt = metrics["headline"], metrics["gate"], metrics["traps"]["metadata_kept"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    return f"""# Decision memo: newsgroup topic classifier

{_banner(metrics)}Generated by `python -m text_classification.report` from `results/`. Do not edit by hand.

## The question
Is a TF-IDF classifier accurate enough to route posts to topics as a first pass, and does a heavier model pay for itself over Naive Bayes?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline {head["model"]} has test macro-F1 {head["value"]:.4f} (95% interval {head["ci95"][0]:.4f} to {head["ci95"][1]:.4f}), against a majority baseline of {metrics["baseline"]["test_macro_f1"]:.4f}. Gain over Naive Bayes, 95% interval: {_fmt_ci(metrics["gain_over_naive_bayes_ci95"])}.

## What a wrong answer costs
A misrouted post lands with the wrong reviewers. The weakest classes and most confused pairs in the model card show where this happens. This project has no cost of a misroute, so no cost-weighted verdict is given.

## What would have fooled us
Leaving headers, footers, and quotes in the text scores {mt["test_macro_f1_metadata_kept"]:.4f}, a change of {mt["difference"]:+.4f}. That score measures who posted, not what the post says. Report the cleaned number.

## Not done
No transformer comparison. No cost-weighted metric. No calibration of predicted probabilities. No test on text from a different source or period.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
