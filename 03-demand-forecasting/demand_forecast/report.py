"""Render the model card and decision memo from results/. No number is typed here.

python -m demand_forecast.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != "bike_sharing_uci":
        return "> **Not a release result.** Generated from a fast or synthetic run. Do not cite these numbers.\n\n"
    return ""


def render_model_card(metrics: dict, analysis: dict) -> str:
    head, base, bt = metrics["headline"], metrics["best_baseline"], metrics["backtest"]
    traps = metrics["traps"]
    rows = "\n".join(
        f"| {n} | {r['tuning_mae']:.1f} | {r['test_mae']:.1f} | {r['test_rmse']:.1f} | "
        f"{r['test_smape_percent']:.1f} | {r['test_mase']:.3f} | {r['test_bias']:+.1f} |"
        for n, r in metrics["models"].items()
    )
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    gap = metrics["gap_best_baseline_minus_headline_ci95"]
    sd, sl, rk = traps["same_day_components"], traps["short_lag"], traps["random_kfold"]
    return f"""# Model card: demand forecasting

{_banner(metrics)}Generated by `python -m demand_forecast.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating a forecast with a rolling-origin backtest and honest features. Not for operating a real bike fleet.

## Data
Daily bike rental counts, {metrics["data"]["rows"]} days. See `data/DATA_CARD.md`.

## Backtest design
Forecast {bt["horizon_days"]} days ahead. {bt["origins"]} rolling origins starting after {bt["initial_train_days"]} days of history, one every {bt["step_days"]} days. The first {bt["tuning_origins"]} origins tune hyperparameters and pick the headline model and best baseline. The last {bt["test_origins"]} origins ({bt["test_days"]} days) are the test, scored once.

## Results
Counts are rentals per day. MASE divides MAE by the in-sample MAE of a 7 day seasonal naive forecast ({bt["mase_scale_seasonal_naive_mae"]:.1f}); below 1 beats that benchmark.

| Model | Tuning MAE | Test MAE | Test RMSE | Test sMAPE % | Test MASE | Test bias |
|---|---|---|---|---|---|---|
{rows}

Headline: **{head["model"]}**, test MAE {head["value"]:.1f}, 95% interval {head["ci95"][0]:.1f} to {head["ci95"][1]:.1f} ({head["ci_method"]}). Best baseline: {base["model"]}, test MAE {base["test_mae"]:.1f}. Gap (baseline minus headline) 95% interval: {gap[0]:.1f} to {gap[1]:.1f}.

## The traps, measured
- Same-day components: MAE {sd["test_mae_with_leak"]:.1f} with the leak versus {sd["test_mae_honest"]:.1f} honest. {sd["note"]}
- Short lags: MAE {sl["test_mae_with_leak"]:.1f} versus {sl["test_mae_honest"]:.1f} honest. {sl["note"]}
- Shuffled folds: MAE {rk["random_5fold_mae"]:.1f} on random 5-fold versus {rk["rolling_origin_test_mae"]:.1f} on the rolling-origin test. {rk["note"]}

## Where it fails
Worst weekday by MAE: **{analysis["worst_weekday"]}** (0 is Sunday). Median fold MAE {analysis["fold_mae"]["median"]:.1f}, worst fold {analysis["fold_mae"]["max"]:.1f}. Full tables are in `results/error_analysis.json`.

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, scikit-learn {metrics["versions"]["scikit-learn"]}, pandas {metrics["versions"]["pandas"]}, numpy {metrics["versions"]["numpy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    head, base, gate = metrics["headline"], metrics["best_baseline"], metrics["gate"]
    gap = metrics["gap_best_baseline_minus_headline_ci95"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    return f"""# Decision memo: weekly demand forecast

{_banner(metrics)}Generated by `python -m demand_forecast.report` from `results/`. Do not edit by hand.

## The question
Can a 7 day ahead daily demand forecast from calendar facts and past demand beat the best simple baseline?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline {head["model"]} has test MAE {head["value"]:.1f} (95% interval {head["ci95"][0]:.1f} to {head["ci95"][1]:.1f}). Best baseline {base["model"]} has test MAE {base["test_mae"]:.1f}. The gap in MAE, baseline minus model, has a 95% interval of {gap[0]:.1f} to {gap[1]:.1f}.

## What a wrong answer costs
A forecast error of about {head["value"]:.0f} rentals a day is the typical miss at this horizon. Whether that matters depends on fleet and staffing costs this project does not have.

## Where not to trust it
Worst weekday: {analysis["worst_weekday"]}. Weather is not an input, so weather-driven swings are missed. Two years of one city is not enough to trust a year-over-year pattern.

## Not done
No weather forecast inputs. No prediction intervals. No hierarchical or multi-location forecasting. No cost model for over- and under-forecasting.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
