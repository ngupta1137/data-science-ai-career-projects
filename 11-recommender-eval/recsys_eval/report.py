"""Render the model card and decision memo from results/. No number is typed here.

python -m recsys_eval.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(block: dict, digits: int = 4) -> str:
    lo, hi = block["ci95"]
    return f"{block['value']:.{digits}f} ({lo:.{digits}f} to {hi:.{digits}f})"


def render_model_card(metrics: dict, analysis: dict) -> str:
    m, d, t = metrics["models"], metrics["data"], metrics["traps"]
    h = metrics["headline"]["model"]
    rows = "\n".join(
        f"| {n} | {_ci(v['ndcg10'])} | {v['hit10']:.3f} | {_ci(v['true_like10'], 3)} | {v['value_captured']:+.3f} | {v['coverage10']:.2f} | {v['gini10']:.2f} |"
        for n, v in m.items()
    )
    rs = t["random_split_inflates_scores"]
    rs_rows = "\n".join(
        f"| {n} | {rs['ndcg10_temporal_test'][n]:.4f} | {rs['ndcg10_random_split'][n]:.4f} |"
        for n in rs["ndcg10_temporal_test"]
    )
    sm = t["sampled_metrics"]
    sm_rows = "\n".join(
        f"| {n} | {v['full_hit10']:.3f} | {v['sampled_hit10']:.3f} |"
        for n, v in sm["by_model"].items()
    )
    ob = t["observed_metric_rewards_the_logging_policy"]
    sweep = "\n".join(
        f"| {r['exposure_strength']:g} | {r['spearman_observed_vs_true']:+.2f} | {' > '.join(r['observed_order'][:3])} | {' > '.join(r['true_order'][:3])} |"
        for r in t["exposure_sweep"]
    )
    seg = "\n".join(
        f"| {r['segment']} | {r['users']} | {r['headline_ndcg10']:.4f} | {r['popularity_ndcg10']:.4f} | {r['headline_true_like10']:.3f} | {r['popularity_true_like10']:.3f} |"
        for r in analysis["by_user_activity"]
    )
    grp = "\n".join(
        f"| {r['item_group']} | {r['held_out_clicks']} | {r[h + '_recall10']:.3f} | {r['popularity_recall10']:.3f} |"
        for r in analysis["by_item_popularity"]
    )
    val = ", ".join(f"{k} {v:.4f}" for k, v in analysis["validation_ndcg10"].items())
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    a = metrics["assumptions"]
    return f"""# Model card: recommender offline evaluation

{_banner(metrics)}Generated by `python -m recsys_eval.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating a recommender offline: a temporal split, ranking metrics, bootstrap intervals over users, and a check on whether the offline metric agrees with what users actually like. Not a production recommender.

## Data
Simulated: {d["users"]} users, {d["items"]} items, {d["clicks"]} logged clicks over {config.HORIZON:g} days. Test window: train on {d["train_clicks_test"]} clicks before day {config.TEST_START:g}, evaluate on {d["holdout_clicks_test"]} clicks after it, for {analysis["eligible_users"]} users with history and a held-out click. See `data/DATA_CARD.md`.

## Assumptions
Items are shown by a policy that favours popular ones (strength {a["exposure_strength"]:g}). A user clicks a shown item with probability sigmoid({a["click_beta"]:g} * affinity {a["click_bias"]:+g}). Taste drifts by {a["drift"]:g} over the horizon. All are assumptions about a made-up service.

## Results on the test window
Observed columns use held-out clicks. True columns use the simulator's affinities and are not available in real data. "Value captured" rescales the true like rate so random is 0 and the oracle is 1. Intervals are percentile bootstrap over users.

| Model | NDCG@10 (observed) | Hit rate@10 (observed) | True like rate@10 | Value captured | Item coverage@10 | Gini of exposure |
|---|---|---|---|---|---|---|
{rows}

Headline: **{h}** ({metrics["headline"]["selected_by"]}). Validation NDCG@10: {val}.

## The traps, measured
- The observed metric rewards the logging policy. Models ordered by observed NDCG@10: {" > ".join(ob["observed_order"])}. By true like rate: {" > ".join(ob["true_order"])}. Spearman correlation {ob["spearman_observed_vs_true"]:+.2f}. The oracle, which knows what users like, scores {ob["oracle_observed_ndcg10"]:.4f} against popularity's {ob["popularity_observed_ndcg10"]:.4f}. {ob["note"]}
- Popularity scores below random on true like rate. This is a selection effect, not a defect in the metric: popular items are liked about as much as any item on average, but once the items a user already clicked are removed, what remains is mostly popular items the user was shown and passed on.
- Cold start: {t["cold_start_ceiling"]["share_of_test_clicks_on_items_unseen_in_training"]:.3f} of test clicks are on items the training window never saw. {t["cold_start_ceiling"]["note"]}

### Random split versus temporal split
NDCG@10 against held-out clicks.

| Model | Temporal test | Random 80/20 split of events |
|---|---|---|
{rs_rows}

{rs["note"]}

### Sampled metrics
Hit rate at 10 when each click is ranked against all items (full) and against {config.SAMPLED_NEGATIVES} random items (sampled).

| Model | Full | Sampled |
|---|---|---|
{sm_rows}

Spearman correlation between the two orderings of models: {sm["spearman_sampled_vs_full"]:+.2f}. {sm["note"]}

### Exposure sweep
Same world, only the logging policy's preference for popular items changes. Spearman is between observed NDCG@10 and true like rate across the seven models.

| Exposure strength | Spearman | Top 3 by observed | Top 3 by truth |
|---|---|---|---|
{sweep}

## Where the headline errs
By user activity (clicks before the test window):

| Segment | Users | Headline NDCG@10 | Popularity NDCG@10 | Headline true like rate | Popularity true like rate |
|---|---|---|---|---|---|
{seg}

By item popularity (recall@10 of held-out clicks on items in each third):

| Item group | Held-out clicks | {h} | popularity |
|---|---|---|---|
{grp}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    hd, gate, m, t = metrics["headline"], metrics["gate"], metrics["models"], metrics["traps"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    h = hd["model"]
    do, dt = hd["minus_popularity_observed_ndcg10"], hd["minus_popularity_true_like10"]
    best_true = max(config.CANDIDATES, key=lambda n: m[n]["true_like10"]["value"])
    val = analysis["validation_ndcg10"]
    sweep = {r["exposure_strength"]: r["spearman_observed_vs_true"] for r in t["exposure_sweep"]}
    low = min(sweep)
    return f"""# Decision memo: can offline NDCG decide which recommender to ship?

{_banner(metrics)}Generated by `python -m recsys_eval.report` from `results/`. Do not edit by hand.

## The question
A personalised recommender is proposed to replace popularity. Offline, on logged clicks, can we tell whether it is better, and which one to ship?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline model: {h}.
{checks}

Against popularity, {h} gains {do["value"]:+.4f} NDCG@10 ({do["ci95"][0]:+.4f} to {do["ci95"][1]:+.4f}) and {dt["value"]:+.4f} true like rate ({dt["ci95"][0]:+.4f} to {dt["ci95"][1]:+.4f}). Across the seven models, the offline metric and the true like rate have Spearman correlation {hd["spearman_observed_vs_true"]:+.2f}. The bar was {metrics["assumptions"]["spearman_floor"]:g}.

## Why passing the first two checks is not good news
Both checks compare against popularity, and popularity is worse than random on true like rate here ({m["popularity"]["true_like10"]["value"]:.3f} against {m["random"]["true_like10"]["value"]:.3f}). The headline, {h}, has true like rate {m[h]["true_like10"]["value"]:.3f}, {"below" if m[h]["true_like10"]["value"] < m["random"]["true_like10"]["value"] else "above"} random. Beating a bad baseline is a low bar, and the gate was written with that baseline.

## The offline metric picked the wrong model
Validation NDCG@10 ranked the candidates {" > ".join(sorted(val, key=lambda k: -val[k]))}. By true like rate the best candidate is {best_true} ({m[best_true]["true_like10"]["value"]:.3f}, value captured {m[best_true]["value_captured"]:+.3f}), not {h} ({m[h]["true_like10"]["value"]:.3f}, {m[h]["value_captured"]:+.3f}). The oracle, which knows what users like, ranks near the bottom on observed NDCG@10. The cause is exposure: held-out clicks come from a policy that shows popular items, so the metric rewards showing popular items. When the logging policy shows items evenly (exposure strength {low:g}) the Spearman correlation is {sweep[low]:+.2f}; at the default strength it is {sweep[config.EXPOSURE_STRENGTH]:+.2f}.

## What to do instead
Do not choose between models on NDCG against logged clicks from a popularity-biased policy. Run a small randomised exposure (or an online test) to get unbiased feedback, weight clicks by an estimated exposure propensity, and judge on that. In this project the inverse-popularity weighting (fixed exponent {config.IPS_ALPHA:g}) took the true like rate from {m["svd"]["true_like10"]["value"]:.3f} (svd) to {m["svd_ips"]["true_like10"]["value"]:.3f} (svd_ips) while observed NDCG@10 fell from {m["svd"]["ndcg10"]["value"]:.4f} to {m["svd_ips"]["ndcg10"]["value"]:.4f}. That is the trade a team has to accept knowingly. It is not a recommendation to use that exponent.

## What a wrong call costs
Shipping {h} instead of {best_true} gives up {m[best_true]["true_like10"]["value"] - m[h]["true_like10"]["value"]:.3f} in like rate at 10, a drop of {(m[best_true]["true_like10"]["value"] - m[h]["true_like10"]["value"]) / m[best_true]["true_like10"]["value"]:.0%} of what {best_true} delivers. The value of a like is an assumption this project does not make.

## Where not to trust it
Everything. The world, the exposure policy and the users are simulated. The point is the mechanism, not the sizes. Items released after training cannot be recommended ({t["cold_start_ceiling"]["share_of_test_clicks_on_items_unseen_in_training"]:.1%} of test clicks). Users with 1 to 4 prior clicks are {analysis["by_user_activity"][0]["users"]} people, too few to read.

## Not done
No online experiment, no off-policy estimator, no neural or sequential model, no tuning, no feedback loop, no cold-start model, no real data.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
