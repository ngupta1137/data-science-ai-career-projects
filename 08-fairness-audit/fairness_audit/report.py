"""Render the model card and decision memo from results/. No number is typed here.

python -m fairness_audit.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _val(block: dict, signed: bool = True) -> str:
    lo, hi = block["ci95"]
    fmt = "+.3f" if signed else ".3f"
    return f"{block['value']:{fmt}} ({lo:{fmt}} to {hi:{fmt}})"


def _opt(block: dict, signed: bool = True) -> str:
    return "n/a" if block["value"] is None else _val(block, signed)


def render_model_card(metrics: dict, analysis: dict) -> str:
    h, d, pol = metrics["headline"], metrics["data"], metrics["policies"]
    a = metrics["assumptions"]
    rows = "\n".join(
        f"| {n} | {_val(p['utility'], False)} | {p['groups']['A']['tpr']:.3f} | "
        f"{p['groups']['B']['tpr']:.3f} | {_val(p['tpr_gap'])} | {_val(p['fpr_gap'])} | "
        f"{_opt(p['ppv_gap'])} | {_opt(p['selection_ratio'], False)} |"
        for n, p in pol.items()
    )
    auc_rows = "\n".join(
        f"| {k} | {v['overall']:.3f} | {v['group_A']:.3f} | {v['group_B']:.3f} |"
        for k, v in metrics["model_auc"].items()
    )
    t = metrics["traps"]
    un, ag, tl = (
        t["fairness_through_unawareness"],
        t["aggregate_auc_hides_group_gap"],
        t["group_thresholds_tuned_on_test"],
    )
    ce, sg = (
        t["cannot_equalize_everything"],
        t["small_group_wide_interval"]["tpr_ci_unaware_single"],
    )
    gz = t["gap_of_zero_is_cheap"]
    sens = "\n".join(
        f"| {r['cost_bad']:g} | {r['single']['utility']:.4f} | {r['single']['tpr_gap']:+.3f} | "
        f"{r['group_thresholds']['utility']:.4f} | {r['group_thresholds']['tpr_gap']:+.3f} |"
        for r in analysis["cost_sensitivity"]
    )
    study = analysis["post_hoc_dev_size_study"]
    study_rows = "\n".join(
        f"| {r['dev_rows']} | {r['mean_large_eval_tpr_gap']:+.3f} | {r['sd_large_eval_tpr_gap']:.3f} | "
        f"{r['share_within_tolerance_large_eval']:.2f} | {r['mean_test_tpr_gap']:+.3f} |"
        for r in study["rows"]
    )
    price = analysis["price_of_equal_opportunity"]
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    return f"""# Model card: fairness and model risk audit

{_banner(metrics)}Generated by `python -m fairness_audit.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for auditing a decision policy by group: measure, find the gap, try a mitigation, and see what it costs. Not a compliance tool and not legal advice.

## Data
Simulated applicants with known mechanisms ({d["fit"]} fit, {d["dev"]} dev, {d["test"]} test rows). Group B is {d["test_group_B_share"]:.2f} of the test set. Base rate of the good outcome: group A {d["test_base_rate_A"]:.3f}, group B {d["test_base_rate_B"]:.3f}. See `data/DATA_CARD.md`.

## Assumptions
Approving a good applicant is worth {a["benefit_good"]:g}; approving a bad one costs {a["cost_bad"]:g}. The tolerance on the true positive rate gap is {a["tpr_gap_tolerance"]:g}. Both are assumptions. Gaps are group B minus group A.

## Policies on the test set
Intervals are group-stratified bootstrap over {d["test"]} rows. Utility is per applicant.

| Policy | Utility | TPR A | TPR B | TPR gap | FPR gap | PPV gap | Selection ratio (min/max) |
|---|---|---|---|---|---|---|---|
{rows}

Headline: **{h["policy"]}** ({h["selected_by"]}). The selection ratio is shown against the {config.SELECTION_RATIO_SCREEN} screening convention for information only; it is not a legal determination.

## Scoring quality by group (AUC)
| Model | Overall | Group A | Group B |
|---|---|---|---|
{auc_rows}

## The traps, measured
- Unawareness: TPR gap {un["tpr_gap_aware"]["value"]:+.3f} with the group column, {un["tpr_gap_unaware"]["value"]:+.3f} without it, {un["tpr_gap_blind_no_proxy"]["value"]:+.3f} without it and without the proxy feature. {un["note"]}
- One AUC: overall {ag["overall_auc"]:.3f}, group A {ag["group_A_auc"]:.3f}, group B {ag["group_B_auc"]:.3f}. {ag["note"]}
- Thresholds tuned on test: TPR gap {tl["tpr_gap_with_leak"]:+.3f} versus {tl["tpr_gap_honest_dev_tuned"]:+.3f} when tuned on dev. {tl["note"]}
- A zero gap is cheap: rejecting everyone has TPR gap {gz["reject_all_tpr_gap"]:+.3f} and utility {gz["reject_all_utility"]:.3f}. {gz["note"]}
- Not everything can be equal: with base rates {ce["base_rate_A"]:.3f} and {ce["base_rate_B"]:.3f}, group thresholds move the gaps from TPR {ce["unaware_single"]["tpr_gap"]:+.3f}, FPR {ce["unaware_single"]["fpr_gap"]:+.3f}, PPV {ce["unaware_single"]["ppv_gap"]:+.3f} to TPR {ce["group_thresholds"]["tpr_gap"]:+.3f}, FPR {ce["group_thresholds"]["fpr_gap"]:+.3f}, PPV {ce["group_thresholds"]["ppv_gap"]:+.3f}. {ce["note"]}
- The small group: the 95% interval on group B's true positive rate is {sg["B"]["width"]:.3f} wide against {sg["A"]["width"]:.3f} for group A.

## Price of equal opportunity
Utility of the single threshold minus utility of group thresholds: {price["utility_difference_single_minus_group_thresholds"]:+.4f}, 95% interval {price["ci95"][0]:+.4f} to {price["ci95"][1]:+.4f} (paired bootstrap).

## Sensitivity to the cost of a bad approval
Threshold re-chosen on dev for each cost, measured on test.

| Cost of bad approval | Utility, single | TPR gap, single | Utility, group thresholds | TPR gap, group thresholds |
|---|---|---|---|---|
{sens}

## Post hoc: how much dev data do group thresholds need?
{study["status"].capitalize()}. Each row repeats the dev draw {study["rows"][0]["replications"]} times and scores the resulting thresholds on a large fresh set that approximates the population. The last column is the gap on the one fixed test set, which carries its own sampling error.

| Dev rows | Mean gap, large set | SD of gap, large set | Share within tolerance | Mean gap, fixed test set |
|---|---|---|---|---|
{study_rows}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, pandas {metrics["versions"]["pandas"]}, scikit-learn {metrics["versions"]["scikit-learn"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    h, gate, pol = metrics["headline"], metrics["gate"], metrics["policies"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    hp = pol[h["policy"]]
    dev = analysis["dev_rows"][h["policy"]]
    gt = pol["unaware_group_thresholds"]
    price = analysis["price_of_equal_opportunity"]
    big = analysis["post_hoc_dev_size_study"]["rows"][-1]
    return f"""# Decision memo: can this decision policy be signed off?

{_banner(metrics)}Generated by `python -m fairness_audit.report` from `results/`. Do not edit by hand.

## The question
Does the chosen approval policy treat the two groups acceptably on true positive rate, while still earning more than rejecting everyone?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline policy: {h["policy"]}.
{checks}

Absolute true positive rate gap on test: {h["value"]:.3f}, 95% interval {h["ci95"][0]:.3f} to {h["ci95"][1]:.3f}. Utility per applicant {hp["utility"]["value"]:.4f} ({hp["utility"]["ci95"][0]:.4f} to {hp["utility"]["ci95"][1]:.4f}).

## Why the headline was chosen, and what that missed
It was chosen on dev because its dev gap was {abs(dev["tpr_gap"]):.3f}, inside the tolerance. On test the gap is {h["value"]:.3f}. A dev set of {metrics["data"]["dev"]} rows holds few group B positives, so a dev gap is a noisy guess. Choosing the best-looking candidate on a noisy number overstates it.

## Equal opportunity thresholds
Group thresholds tuned on dev give a test TPR gap of {gt["tpr_gap"]["value"]:+.3f} (interval {gt["tpr_gap"]["ci95"][0]:+.3f} to {gt["tpr_gap"]["ci95"][1]:+.3f}) at a utility cost of {price["utility_difference_single_minus_group_thresholds"]:+.4f} ({price["ci95"][0]:+.4f} to {price["ci95"][1]:+.4f}). The post hoc study shows these thresholds average a gap of {big["mean_large_eval_tpr_gap"]:+.3f} on a large fresh set when tuned on {big["dev_rows"]} dev rows, so the mitigation works on average. The test set cannot confirm it: with this many group B positives, the upper bound of the interval on the absolute gap is {gt["abs_tpr_gap_ci95"][1]:.3f}, above the {metrics["assumptions"]["tpr_gap_tolerance"]:g} tolerance.

## What a wrong call costs
Signing off a policy that under-serves group B means qualified applicants are refused at a higher rate. Refusing to sign off a fine policy delays a launch. Neither can be priced here, because the costs in this project are assumptions.

## Where not to trust it
The worst-off group by true positive rate is group {analysis["worst_off_group_by_tpr"]}. The data is simulated, there are only two groups, and equal opportunity is one of several definitions. The result says nothing about a real lender or employer.

## Not done
No intersectional groups. No legal analysis. No causal model of where the gap comes from beyond the simulator. No real data. No in-processing or reweighting mitigations.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
