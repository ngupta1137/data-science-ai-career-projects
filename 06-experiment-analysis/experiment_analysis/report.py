"""Render the model card and decision memo from results/. No number is typed here.

python -m experiment_analysis.report
"""

from __future__ import annotations

import json

from . import config


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != config.DATA_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _ci(ci, digits: int = 3) -> str:
    return f"{ci[0]:.{digits}f} to {ci[1]:.{digits}f}"


def _pct(block: dict) -> str:
    return f"{block['rate']:.3f} ({_ci(block['ci95'])})"


def render_model_card(metrics: dict, analysis: dict) -> str:
    h, power, traps = metrics["headline"], metrics["power"], metrics["traps"]
    grid_rows = "\n".join(
        f"| {c['dist']} | {c['n_per_arm']} | {_pct(c['aa']['raw'])} | {_pct(c['aa']['cuped'])} | "
        f"{c['with_effect']['raw']['coverage']['rate']:.3f} | "
        f"{c['with_effect']['cuped']['coverage']['rate']:.3f} | "
        f"{c['with_effect']['raw']['power']['rate']:.2f} | "
        f"{c['with_effect']['cuped']['power']['rate']:.2f} |"
        for c in metrics["fixed_horizon_grid"]
    )
    rho_rows = "\n".join(
        f"| {r['rho']:.1f} | {r['variance_ratio']:.3f} ({_ci(r['variance_ratio_ci95'])}) | "
        f"{r['theory_ratio']:.3f} | {r['cuped_mean_error']:+.4f} |"
        for r in metrics["cuped_by_rho"]
    )
    peek_rows = "\n".join(
        f"| {r['looks']} | {_pct(r['naive_false_positive'])} | {_pct(r['bonferroni_false_positive'])} |"
        for r in metrics["peeking"]
    )
    mm = metrics["multiple_metrics"]
    multi_rows = "\n".join(
        f"| {name} | {_pct(mm['all_null'][name]['family_wise_error'])} | "
        f"{_pct(mm['two_true'][name]['family_wise_error'])} | "
        f"{mm['two_true'][name]['power_per_true_metric']['rate']:.3f} |"
        for name in ("uncorrected", "bonferroni", "holm")
    )
    flagged = analysis["false_positive_rate_outside_nominal"]
    flagged_text = (
        "\n".join(
            f"- {f['method']}, {f['dist']}, {f['n_per_arm']} per arm: false positive rate "
            f"{f['false_positive_rate']:.3f} ({_ci(f['ci95'])})"
            for f in flagged
        )
        or "- none"
    )
    low_cov = analysis["interval_coverage_below_95"]
    low_cov_text = (
        "\n".join(
            f"- {f['method']}, {f['dist']}, {f['n_per_arm']} per arm: coverage "
            f"{f['coverage']:.3f} ({_ci(f['ci95'])})"
            for f in low_cov
        )
        or "- none"
    )
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    cc = traps["contaminated_covariate"]
    pk, um, ht = traps["peeking"], traps["uncorrected_metrics"], traps["heavy_tail_small_sample"]
    return f"""# Model card: experiment analysis methods

{_banner(metrics)}Generated by `python -m experiment_analysis.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for checking, by simulation, how often common A/B analysis methods are wrong. Not a substitute for an experimentation platform.

## Data
Simulated experiments with a known true effect ({metrics["data"]["experiments_per_cell"]} per cell; {metrics["data"]["headline_aa_experiments"]} A/A experiments at the headline cell). See `data/DATA_CARD.md`.

## Headline
CUPED with a fixed horizon, {h["n_per_arm"]} users per arm, correlation {h["rho"]}: the variance of the estimate is **{h["value"]:.3f}** times the raw estimate's variance (95% interval {_ci(h["ci95"])}, {h["ci_method"]}). Theory says {h["theory"]:.3f}.

## Fixed-horizon grid
False positive rate is from A/A experiments (nominal 0.05). Coverage is of the 95% interval for a true effect of {config.TRUE_EFFECT} standard deviations. Power is at that effect.

| Outcome | n per arm | False positive, raw | False positive, CUPED | Coverage, raw | Coverage, CUPED | Power, raw | Power, CUPED |
|---|---|---|---|---|---|---|---|
{grid_rows}

## CUPED by correlation
| rho | Variance ratio (interval) | Theory 1 - rho^2 | CUPED mean error |
|---|---|---|---|
{rho_rows}

## Power and sample size
Target power {power["target_power"]}, effect {power["effect"]}. Formula gives {power["raw"]["n_per_arm"]} per arm raw and {power["cuped"]["n_per_arm"]} with CUPED ({power["users_saved_percent"]:.1f}% fewer users). Simulated power: raw {_pct(power["raw"]["simulated_power"])}, CUPED {_pct(power["cuped"]["simulated_power"])}.

## Peeking (A/A, {config.PEEK_N} users per arm)
| Looks | Stop at first significant look | Bonferroni over looks |
|---|---|---|
{peek_rows}

## Multiple metrics ({mm["metrics"]} metrics, {mm["n_per_arm"]} users per arm)
Family-wise error is the chance of at least one false rejection. Power is per true effect of {mm["true_effect"]}.

| Rule | FWER, all null | FWER, two true | Power per true metric |
|---|---|---|---|
{multi_rows}

## The traps, measured
- Peeking: stopping at the first significant of {pk["looks"]} looks gives {_pct(pk["naive_false_positive"])} false positives instead of 0.05.
- Ten metrics, no correction: {_pct(um["uncorrected_family_wise_error"])} chance of at least one false positive. Holm: {_pct(um["holm_family_wise_error"])}.
- Skewed data, few users ({ht["n_per_arm"]} per arm): raw false positive rate {_pct(ht["lognormal_raw_false_positive"])} on lognormal versus {_pct(ht["normal_raw_false_positive"])} on normal.
- Contaminated covariate: CUPED mean error {cc["cuped_mean_error_contaminated_covariate"]:+.3f} against a true effect of {cc["true_effect"]}, interval coverage {cc["cuped_coverage_contaminated"]["rate"]:.3f}. With a clean covariate the error is {cc["cuped_mean_error_clean_covariate"]:+.4f}. {cc["note"]}

## Where it fails
False positive rate outside nominal (95% interval excludes 0.05):
{flagged_text}

Interval coverage clearly below 95%:
{low_cov_text}

{len(analysis["grid"]) * 2} method and cell pairs are checked for each list, so one or two flags can occur by chance. Treat a flag as a lead, not a proof, unless it is large or repeats across cells.

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, numpy {metrics["versions"]["numpy"]}, scipy {metrics["versions"]["scipy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    h, gate, power, traps = metrics["headline"], metrics["gate"], metrics["power"], metrics["traps"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    checks = "\n".join(f"- {k}: {v}" for k, v in gate["checks"].items())
    pk, cc = traps["peeking"], traps["contaminated_covariate"]
    return f"""# Decision memo: which A/B analysis defaults to adopt

{_banner(metrics)}Generated by `python -m experiment_analysis.report` from `results/`. Do not edit by hand.

## The question
Can a team adopt CUPED with a fixed horizon and Holm correction as its default analysis, and trust the false positive rate and the interval?

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
{checks}

CUPED cut the variance to {h["value"]:.3f} of the raw estimate ({_ci(h["ci95"])}), which cuts the users needed by {power["users_saved_percent"]:.1f}% at correlation {h["rho"]}.

## What a wrong analysis costs
Peeking at {pk["looks"]} looks gives a false positive rate of {pk["naive_false_positive"]["rate"]:.3f}, about {pk["naive_false_positive"]["rate"] / 0.05:.1f} times the nominal 0.05. Each false positive ships a change that does nothing. A covariate that moves with treatment turns CUPED into a machine that removes real effect: mean error {cc["cuped_mean_error_contaminated_covariate"]:+.3f} against a true effect of {cc["true_effect"]}.

## Where not to trust it
Small samples. The grid flags cells where the false positive rate or interval coverage is off. A likely cause for CUPED is that the standard error ignores the estimated coefficient, but this project does not test that. Heavy tails with few users are another risk. See the flagged cells in the model card.

## Not done
No sequential designs with alpha spending or always-valid intervals. No sample ratio mismatch check. No interference, novelty effects, or repeated measures. No real experiment data.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
