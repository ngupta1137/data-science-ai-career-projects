"""Render the model card and decision memo from results/. No number is typed here.

python -m rag_eval.report
"""

from __future__ import annotations

import json

from . import config

RELEASE_SOURCE = "generated_teaching_corpus"


def _banner(metrics: dict) -> str:
    if metrics["fast_mode"] or metrics["data_source"] != RELEASE_SOURCE:
        return "> **Not a release result.** Generated from a fast or test run. Do not cite these numbers.\n\n"
    return ""


def _opt(value) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _ci(ci) -> str:
    return f"{ci[0]:.3f} to {ci[1]:.3f}"


def render_model_card(metrics: dict, analysis: dict) -> str:
    head, e2e, sel = metrics["headline"], metrics["end_to_end"], metrics["selection"]
    d, traps = metrics["data"], metrics["traps"]
    rows = "\n".join(
        f"| {n} | {r['test_recall_at_1']:.3f} | {r['test_recall_at_3']:.3f} | "
        f"{r['test_mrr']:.3f} | {r['test_ndcg_at_5']:.3f} |"
        for n, r in metrics["retrieval"].items()
    )
    type_rows = "\n".join(
        f"| {t} | {r['n']} | {_opt(r.get('gold_in_top_k'))} | {r['end_to_end_correct']:.3f} |"
        for t, r in analysis["by_type"].items()
    )
    tax = "\n".join(f"- {k}: {v}" for k, v in e2e["taxonomy"].items())
    caveats = "\n".join(f"- {c}" for c in metrics["caveats"])
    th, ao, an = (
        traps["threshold_tuned_on_test"],
        traps["answer_everything"],
        traps["answerable_only"],
    )
    return f"""# Model card: retrieval and answering evaluation

{_banner(metrics)}Generated by `python -m rag_eval.report` from `results/metrics.json`. Do not edit by hand.

## Intended use
Learning. A reference for evaluating retrieval and answering separately, including refusal. Not a production question answering system.

## Data
{d["documents"]} generated documents and {d["questions"]} questions about a fictional company ({d["dev_questions"]} dev, {d["test_questions"]} test, of which {d["test_answerable"]} answerable). See `data/DATA_CARD.md`.

## Design
Retriever settings and the headline retriever are chosen on dev questions only: BM25 k1 {sel["bm25"]["k1"]}, b {sel["bm25"]["b"]}; LSA {sel["lsa_dims"]} dimensions. The reader sees the top {sel["context_documents"]} documents. The abstention threshold is {sel["abstention_threshold"]:.3f}, chosen on dev.

## Retrieval, answerable test questions
| Retriever | Recall@1 | Recall@3 | MRR | nDCG@5 |
|---|---|---|---|---|
{rows}

Headline: **{head["retriever"]}**, test MRR {head["value"]:.3f}, 95% interval {_ci(head["ci95"])} ({head["ci_method"]}). Paired MRR gain over BM25, 95% interval: {_ci(metrics["mrr_gain_over_bm25_ci95"])}.

## End to end, all test questions
Correct means: the right value for answerable questions, a refusal for unanswerable ones.

- End-to-end correct: **{e2e["correct"]:.3f}**, 95% interval {_ci(e2e["ci95"])}.
- Always-abstain policy: {e2e["always_abstain_correct"]:.3f}.
- Reader given the gold documents (exact match): {e2e["reader_given_gold_context_exact_match"]:.3f}.
- Confidence as a detector of answerable versus unanswerable (AUC, 0.5 is chance): {e2e["confidence_auc_answerable_vs_unanswerable"]:.3f}.

| Question type | n | Gold doc in top {sel["context_documents"]} | End-to-end correct |
|---|---|---|---|
{type_rows}

## Failure taxonomy (test)
{tax}

Each failing question is listed in `results/error_analysis.json`.

## The traps, measured
- Threshold tuned on test: {th["correct_with_leak"]:.3f} versus {th["correct_honest"]:.3f} honest. {th["note"]}
- Never abstaining: {ao["correct_without_abstention"]:.3f} versus {ao["correct_honest"]:.3f} with the dev threshold. {ao["note"]}
- Answerable questions only: {an["correct_answerable_only"]:.3f} versus {an["correct_all_questions"]:.3f} on all questions. {an["note"]}

## Limits
{caveats}

## Versions
Seed {metrics["seed"]}. Python {metrics["versions"]["python"]}, scikit-learn {metrics["versions"]["scikit-learn"]}, pandas {metrics["versions"]["pandas"]}, numpy {metrics["versions"]["numpy"]}.
"""


def render_decision_memo(metrics: dict, analysis: dict) -> str:
    head, e2e, gate = metrics["headline"], metrics["end_to_end"], metrics["gate"]
    verdict = "PASS" if gate["passed"] else "FAIL"
    tax = e2e["taxonomy"]
    n_unans = tax.get("correct_refusal", 0) + tax.get("answered_unanswerable", 0)
    refusal = tax.get("correct_refusal", 0)
    worst = max(
        (k for k in tax if k not in ("correct", "correct_refusal")), key=tax.get, default="none"
    )
    return f"""# Decision memo: does this pipeline clear the minimum bar?

{_banner(metrics)}Generated by `python -m rag_eval.report` from `results/`. Do not edit by hand.

## The question
Does retrieval plus a simple reader beat a system that always refuses? This is a minimum bar, not a ship decision.

## The rule, set before results were seen
{gate["rule"]}

## The call: {verdict}
Headline retriever {head["retriever"]}, test MRR {head["value"]:.3f} (95% interval {_ci(head["ci95"])}). End-to-end correct {e2e["correct"]:.3f} (95% interval {_ci(e2e["ci95"])}) against {e2e["always_abstain_correct"]:.3f} for always abstaining. Condition 1, end to end beats always abstain: {gate["end_to_end_beats_always_abstain"]}. Condition 2, retrieval gain over BM25: {gate["retrieval_gain_over_bm25"]}.

## Refusal
Of {n_unans} unanswerable test questions, the system correctly refused {refusal}. Passing the gate means it beats always refusing on the combined score. It does not mean it refuses well. The gate is a low bar and a reader should treat it that way.

## What a wrong answer costs
An answer given to an unanswerable question looks the same as a correct one to the reader of the answer. In this run the most frequent failure is **{worst}** ({tax.get(worst, 0)} questions). The reader alone, given the right documents, scores {e2e["reader_given_gold_context_exact_match"]:.3f}, so the losses are upstream of reading.

## Where not to trust it
Refusal is the weakest part. The confidence AUC is {e2e["confidence_auc_answerable_vs_unanswerable"]:.3f} (0.5 is chance), so no threshold can fix it. The confidence signal is word overlap between the question and one sentence. A question that names a real policy but asks about something it does not state overlaps as much as a real question. See the taxonomy and `results/error_analysis.json`.

## Not done
No language model reader or judge. No dense neural retriever. No real documents. No latency or cost measurement.
"""


def main() -> None:
    metrics = json.loads((config.RESULTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    analysis = json.loads((config.RESULTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORTS_DIR / "model_card.md").write_text(
        render_model_card(metrics, analysis), encoding="utf-8"
    )
    (config.REPORTS_DIR / "decision_memo.md").write_text(
        render_decision_memo(metrics, analysis), encoding="utf-8"
    )
    print(f"wrote reports to {config.REPORTS_DIR}")


if __name__ == "__main__":
    main()
